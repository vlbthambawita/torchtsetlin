"""Aggregate the run records into REPORT.md, results/summary.json and figures (plan §6, Phase 4).

Every number comes from ``results/<arm>/*.json`` (rule R2). Cell statistic (D4): test accuracy at
the best-validation epoch, mean ± sd over seeds; ``B*(C)`` (D9): the largest batch whose cell mean
is within 0.3 pp of the B = 1 cell and within 2 sd of it.

Usage: python code/report.py                 # all arms -> REPORT.md, results/summary.json, figures/
       python code/report.py --arm smoke     # -> REPORT_smoke.md (no figures)
       python code/report.py --paper         # also write the paper's generated/ tables + figures
"""

import argparse
import glob
from collections import defaultdict

import numpy as np

from common import BATCHES, CLAUSES, PAPER, PROG, RESULTS, read_json, write_json

TOL_PP = 0.3


def load(arm):
    return [r for r in (read_json(f) for f in sorted(glob.glob(str(RESULTS / arm / "*.json"))))
            if r.get("kind") == "run"]


def cells(recs):
    out = defaultdict(list)
    for r in recs:
        h = r["hp"]
        key = (h["model"], h["clauses_per_class"], h["batch_size"], h["T_mode"], h["feedback_mode"])
        out[key].append(r)
    return out


def stat(rs, k):
    v = np.array([r[k] for r in rs if r.get("status") == "done" and r.get(k) is not None], float)
    if not len(v):
        return None
    return dict(mean=float(v.mean()), sd=float(v.std(ddof=1)) if len(v) > 1 else 0.0, n=int(len(v)))


def fmt(s, nd=2):
    if s is None:
        return "–"
    return f"{s['mean']:.{nd}f}" + (f" ± {s['sd']:.{nd}f}" if s["n"] > 1 else "") + \
        ("" if s["n"] >= 3 else f" (n={s['n']})")


def b_star(table, model, c):
    ref = table.get((model, c, 1))
    if ref is None:
        return None
    best = None
    for b in BATCHES:
        s = table.get((model, c, b))
        if s is None:
            continue
        gap = ref["mean"] - s["mean"]
        if gap <= TOL_PP and gap <= 2 * max(ref["sd"], s["sd"], 1e-9) or b == 1:
            best = b
    return best


def summarise(recs):
    cs = cells(recs)
    rows = []
    for (m, c, b, tm, fm), rs in sorted(cs.items()):
        rows.append(dict(model=m, clauses=c, batch=b, T_mode=tm, feedback_mode=fm,
                         n_runs=len(rs), n_done=sum(r.get("status") == "done" for r in rs),
                         test_acc_at_best=stat(rs, "test_acc_at_best"),
                         best_val_acc=stat(rs, "best_val_acc"), best_epoch=stat(rs, "best_epoch"),
                         epochs_run=stat(rs, "epochs_run"), test_acc_epoch30=stat(rs, "test_acc_epoch30"),
                         gpu_s_to_best=stat(rs, "gpu_s_to_best"),
                         train_s_per_epoch=stat(rs, "train_s_per_epoch_mean"),
                         peak_gpu_mib=stat(rs, "peak_gpu_mib"),
                         stop_reasons=sorted(r.get("stop_reason") or r.get("status") for r in rs),
                         gpus=sorted({r["env"].get("gpu", "cpu") for r in rs})))
    return rows


def grid_md(rows, model, key, nd=2, t_mode="scaled"):
    tab = {(r["clauses"], r["batch"]): r[key] for r in rows
           if r["model"] == model and r["T_mode"] == t_mode and r["feedback_mode"] == "batch"}
    head = "| C/class | " + " | ".join(f"B={b}" for b in BATCHES) + " |"
    lines = [head, "|---" * (len(BATCHES) + 1) + "|"]
    for c in CLAUSES:
        if any((c, b) in tab for b in BATCHES):
            lines.append(f"| {c} | " + " | ".join(fmt(tab.get((c, b)), nd) for b in BATCHES) + " |")
    return "\n".join(lines)


def report(arm_list, out_md, figures, paper):
    allrows = {}
    md = ["# MNIST: batch size × clauses per class, flat vs convolutional TM", "",
          "Generated by `code/report.py` from `results/<arm>/*.json`; do not hand-edit. "
          "Plan: `plans/mnist-batch-clauses.md`.", "",
          "Cell = test accuracy (%) at the best-validation epoch, mean ± sd over seeds (D4). "
          f"B\\*(C) = largest batch within {TOL_PP} pp and 2 sd of B = 1 (D9).", ""]
    for arm in arm_list:
        recs = load(arm)
        if not recs:
            continue
        rows = summarise(recs)
        allrows[arm] = rows
        done = sum(r.get("status") == "done" for r in recs)
        md += [f"## Arm `{arm}`: {done}/{len(recs)} runs done", ""]
        versions = sorted({r["env"]["torchtsetlin"] for r in recs})
        md += [f"torchtsetlin {', '.join(versions)}; GPUs: "
               f"{', '.join(sorted({r['env'].get('gpu', 'cpu') for r in recs}))}.", ""]
        t_modes = sorted({r["T_mode"] for r in rows})
        for model in ("flat", "conv"):
            if not any(r["model"] == model for r in rows):
                continue
            for tm in t_modes:
                if not any(r["model"] == model and r["T_mode"] == tm and r["feedback_mode"] == "batch"
                           for r in rows):
                    continue
                md += [f"### {model}, T {tm}: test accuracy at best epoch", "",
                       grid_md(rows, model, "test_acc_at_best", 2, tm), ""]
                md += [f"### {model}, T {tm}: best epoch", "", grid_md(rows, model, "best_epoch", 0, tm), ""]
                md += [f"### {model}, T {tm}: train s/epoch", "",
                       grid_md(rows, model, "train_s_per_epoch", 1, tm), ""]
                tab = {(r["clauses"], r["batch"]): r["test_acc_at_best"] for r in rows
                       if r["model"] == model and r["T_mode"] == tm and r["test_acc_at_best"]}
                bs = {c: b_star({(model, cc, bb): v for (cc, bb), v in tab.items()}, model, c)
                      for c in CLAUSES}
                if any(v is not None for v in bs.values()):
                    md += ["B\\*(C): " + ", ".join(f"{c}: {v}" for c, v in bs.items() if v is not None), ""]
            seq = [r for r in rows if r["model"] == model and r["feedback_mode"] == "sequential"]
            for r in seq:
                md += [f"- {model} C={r['clauses']} sequential (B={r['batch']}): "
                       f"{fmt(r['test_acc_at_best'])}, best epoch {fmt(r['best_epoch'], 0)}"]
            if seq:
                md += [""]
        stops = defaultdict(int)
        for r in recs:
            stops[r.get("stop_reason") or r.get("status")] += 1
        md += ["Stop reasons: " + ", ".join(f"{k} {v}" for k, v in sorted(stops.items())), ""]
    (PROG / out_md).write_text("\n".join(md) + "\n")
    if out_md == "REPORT.md":
        write_json(allrows, RESULTS / "summary.json")
    if figures and "grid" in allrows:
        plot(allrows["grid"], PROG / "figures", paper)
    if paper and "grid" in allrows:
        write_tex(allrows["grid"])
    print(f"wrote {out_md}")


def plot(rows, outdir, paper):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    outdir.mkdir(parents=True, exist_ok=True)
    grid = [r for r in rows if r["T_mode"] == "scaled" and r["feedback_mode"] == "batch"]
    models = [m for m in ("flat", "conv") if any(r["model"] == m for r in grid)]
    blues = plt.get_cmap("Blues")
    ccol = {c: blues(0.35 + 0.65 * i / (len(CLAUSES) - 1)) for i, c in enumerate(CLAUSES)}

    def series(model, key):
        out = {}
        for c in CLAUSES:
            pts = [(r["batch"], r[key]["mean"], r[key]["sd"]) for r in grid
                   if r["model"] == model and r["clauses"] == c and r[key]]
            if pts:
                out[c] = sorted(pts)
        return out

    # 1. heatmaps
    fig, axes = plt.subplots(1, len(models), figsize=(5.2 * len(models), 3.6), squeeze=False)
    for ax, m in zip(axes[0], models):
        a = np.full((len(CLAUSES), len(BATCHES)), np.nan)
        for r in grid:
            if r["model"] == m and r["test_acc_at_best"]:
                a[CLAUSES.index(r["clauses"]), BATCHES.index(r["batch"])] = r["test_acc_at_best"]["mean"]
        im = ax.imshow(a, cmap="Blues", aspect="auto", origin="lower")
        for i in range(a.shape[0]):
            for j in range(a.shape[1]):
                if not np.isnan(a[i, j]):
                    ax.text(j, i, f"{a[i, j]:.1f}", ha="center", va="center", fontsize=7,
                            color="white" if a[i, j] > np.nanmean(a) else "#222")
        ax.set_xticks(range(len(BATCHES)), BATCHES)
        ax.set_yticks(range(len(CLAUSES)), [f"{c // 1000}k" for c in CLAUSES])
        ax.set_xlabel("batch size B")
        ax.set_ylabel("clauses per class")
        ax.set_title(f"{m} TM: test accuracy (%)")
        fig.colorbar(im, ax=ax, shrink=0.8)
    fig.tight_layout()
    save(fig, outdir, "batch_clauses_heatmap", paper)

    # 2./4. accuracy and epochs-to-best vs B
    for key, ylabel, name in (("test_acc_at_best", "test accuracy at best epoch (%)", "batch_clauses_acc"),
                              ("best_epoch", "epochs to best validation", "batch_clauses_epochs")):
        fig, axes = plt.subplots(1, len(models), figsize=(5.2 * len(models), 3.4), squeeze=False)
        for ax, m in zip(axes[0], models):
            for c, pts in series(m, key).items():
                x = [BATCHES.index(p[0]) for p in pts]
                y, sd = np.array([p[1] for p in pts]), np.array([p[2] for p in pts])
                ax.plot(x, y, "-o", lw=2, ms=4, color=ccol[c], label=f"{c // 1000}k")
                ax.fill_between(x, y - sd, y + sd, color=ccol[c], alpha=0.15, lw=0)
            ax.set_xticks(range(len(BATCHES)), BATCHES)
            ax.set_xlabel("batch size B")
            ax.set_ylabel(ylabel)
            ax.set_title(f"{m} TM")
            ax.grid(alpha=0.25, lw=0.5)
            ax.legend(title="clauses/class", fontsize=7, title_fontsize=7, frameon=False)
        fig.tight_layout()
        save(fig, outdir, name, paper)

    # 3. Pareto: accuracy vs GPU-seconds to best (seed-0 timings, 3090)
    fig, axes = plt.subplots(1, len(models), figsize=(5.2 * len(models), 3.4), squeeze=False)
    bcol = {b: plt.get_cmap("Blues")(0.3 + 0.7 * i / (len(BATCHES) - 1)) for i, b in enumerate(BATCHES)}
    for ax, m in zip(axes[0], models):
        for r in grid:
            if r["model"] == m and r["test_acc_at_best"] and r["gpu_s_to_best"]:
                ax.scatter(r["gpu_s_to_best"]["mean"], r["test_acc_at_best"]["mean"], s=18,
                           color=bcol[r["batch"]], edgecolor="white", lw=0.5)
        for b in BATCHES:
            ax.scatter([], [], color=bcol[b], label=f"B={b}", s=18)
        ax.set_xscale("log")
        ax.set_xlabel("GPU seconds to best epoch")
        ax.set_ylabel("test accuracy at best epoch (%)")
        ax.set_title(f"{m} TM")
        ax.grid(alpha=0.25, lw=0.5)
        ax.legend(fontsize=6, frameon=False, ncol=2)
    fig.tight_layout()
    save(fig, outdir, "batch_clauses_pareto", paper)


def save(fig, outdir, name, paper):
    fig.savefig(outdir / f"{name}.png", dpi=150)
    if paper:
        fig.savefig(PAPER / "figures" / f"{name}.pdf")
    import matplotlib.pyplot as plt
    plt.close(fig)


def write_tex(rows):
    """Paper tables (one per model) and \\R{bc/<model>/c<C>/b<B>} macros."""
    gen = PAPER / "generated"
    macros = ["% generated by experiments/mnist_batch_clauses/code/report.py; do not edit",
              "\\providecommand{\\R}[1]{\\ifcsname R@#1\\endcsname\\csname R@#1\\endcsname"
              "\\else\\textcolor{red}{??#1}\\fi}"]
    for m in ("flat", "conv"):
        tab = {(r["clauses"], r["batch"]): r for r in rows
               if r["model"] == m and r["T_mode"] == "scaled" and r["feedback_mode"] == "batch"}
        if not tab:
            continue
        lines = ["% generated by experiments/mnist_batch_clauses/code/report.py; do not edit",
                 "\\begin{tabular}{@{}r" + "r" * len(BATCHES) + "@{}}", "\\toprule",
                 "$C$ & " + " & ".join(str(b) for b in BATCHES) + " \\\\", "\\midrule"]
        for c in CLAUSES:
            cell = []
            for b in BATCHES:
                s = tab.get((c, b), {}).get("test_acc_at_best")
                cell.append("--" if s is None else f"{s['mean']:.2f}{{\\tiny$\\pm${s['sd']:.2f}}}")
                if s is not None:
                    macros.append(f"\\expandafter\\def\\csname R@bc/{m}/c{c}/b{b}\\endcsname{{{s['mean']:.2f}}}")
            lines.append(f"{c // 1000}k & " + " & ".join(cell) + " \\\\")
        lines += ["\\bottomrule", "\\end{tabular}"]
        (gen / f"batch_clauses_{m}_table.tex").write_text("\n".join(lines) + "\n")
    (gen / "batch_clauses_numbers.tex").write_text("\n".join(macros) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--arm", default=None)
    ap.add_argument("--paper", action="store_true")
    args = ap.parse_args()
    if args.arm:
        report([args.arm], f"REPORT_{args.arm}.md", figures=False, paper=False)
    else:
        report(["grid", "control_T", "control_seq"], "REPORT.md", figures=True, paper=args.paper)


if __name__ == "__main__":
    main()
