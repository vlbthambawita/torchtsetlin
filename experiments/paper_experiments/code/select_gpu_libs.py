"""Rank the GPU-capable libraries from the smoke records (decision of 2026-10-28).

    python code/select_gpu_libs.py [--kind smoke]

For every benchmark it lists each GPU cell (status, accuracy after the smoke epochs, training and
test seconds per epoch, peak GPU memory), then summarises per library: coverage (benchmarks it
runs on the GPU), failures, and the median ratio of its training / test time to torchtsetlin's
best GPU mode on the same benchmark. Writes results/gpu_selection_<kind>.md. Smoke accuracy
after 1 epoch is a sanity check only, never a result (rule P4).
"""
import argparse
import json
import statistics as st
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
RES = HERE / "results"
NAME = {"pytmcuda": "pyTM-CUDA", "tmu": "tmu (GPU)", "tt": "torchtsetlin"}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--kind", default="smoke")
    kind = ap.parse_args().kind
    cells = defaultdict(dict)                     # bench -> label -> row
    for p in sorted((RES / kind).glob("*/*.json")):
        r = json.loads(p.read_text())
        if "cuda" not in str(r.get("device", "")):
            continue
        lib = r["lib"]
        label = lib if r["mode"] == "default" else f"{lib}-{r['mode']}"
        c = r.get("curve") or []
        last = c[-1] if c else {}
        row = {"lib": lib, "status": r.get("status"), "train_s": last.get("train_s"),
               "test_s": last.get("test_s"), "acc": last.get("accuracy"), "rmse": last.get("rmse"),
               "gpu_mib": (r.get("memory") or {}).get("peak_gpu_nvml_mib")}
        cells[r["bench"]][label] = row

    L = [f"# GPU library selection from `results/{kind}`", "",
         "Generated by `code/select_gpu_libs.py`. Times are the last smoke epoch (it includes "
         "compilation when there is only one), so they rank libraries roughly; the timing runs "
         "give the real numbers.", ""]
    ratios = defaultdict(lambda: defaultdict(list))
    fails, cover = defaultdict(list), defaultdict(set)
    order = sorted(cells, key=lambda b: int(b[1:]))
    for b in order:
        L += [f"## {b}", "", "| cell | status | accuracy / RMSE | train s/epoch | test s | peak GPU MiB |",
              "|---|---|---|---|---|---|"]
        for label, r in sorted(cells[b].items()):
            m = r["acc"] if r["acc"] is not None else r["rmse"]
            f = (lambda v, d=3: "—" if v is None else f"{v:.{d}f}")
            L.append(f"| {label} | {r['status']} | {f(m, 4)} | {f(r['train_s'])} | {f(r['test_s'])} | "
                     f"{f(r['gpu_mib'], 0)} |")
            if r["status"] != "done":
                fails[r["lib"]].append(f"{b}/{label}")
            else:
                cover[r["lib"]].add(b)
        tt = [r for k, r in cells[b].items() if r["lib"] == "tt" and r["status"] == "done"
              and "seq" not in k and r["train_s"]]
        if tt:
            best_tr = min(r["train_s"] for r in tt)
            best_te = min(r["test_s"] for r in tt)
            for label, r in cells[b].items():
                if r["lib"] != "tt" and r["status"] == "done" and r["train_s"]:
                    ratios[r["lib"]]["train"].append(r["train_s"] / best_tr)
                    ratios[r["lib"]]["test"].append(r["test_s"] / max(best_te, 1e-4))
        L.append("")
    L += ["## Summary", "", "| library | benchmarks run on the GPU | failed cells | median train time ÷ tt batch | "
          "median test time ÷ tt batch |", "|---|---|---|---|---|"]
    for lib in ("pytmcuda", "tmu", "tt"):
        rt = ratios[lib]
        med = (lambda xs: f"{st.median(xs):.2f}×" if xs else "—")
        L.append(f"| {NAME[lib]} | {len(cover[lib])} ({', '.join(sorted(cover[lib], key=lambda s: int(s[1:])))}) | "
                 f"{', '.join(fails[lib]) or 'none'} | {med(rt['train'])} | {med(rt['test'])} |")
    out = RES / f"gpu_selection_{kind}.md"
    out.write_text("\n".join(L) + "\n")
    print("\n".join(L[-6:]))
    print(f"wrote {out.relative_to(HERE)}")


if __name__ == "__main__":
    main()
