"""Comparison table of the Graph TM reproduction, generated from results/graphtm/*.json only
(PLAN.md rule P2). Writes results/graphtm/REPORT.md and prints it.

Statistic as in the paper (Sec. 3.2): mean test accuracy over the final 5 of 30 epochs; the
paper's +- is over those epochs, so ours is too ("last-5 sd"). Across seeds we report the mean
and sd of that statistic. Pass rule (plan §4): |ours - paper| <= max(1.0 pp, 2 x seed sd).
"""
from __future__ import annotations

import json
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np

RES = Path(__file__).resolve().parents[2] / "results" / "graphtm"
NAMES = {"G0": "Three consecutive A's (Sec. 3.1)", "G1": "MNIST (Table 3)", "G2": "Fashion-MNIST (Table 3)"}
MODELS = {"graph": "GraphTM", "cotm": "CoTM (ConvCoalescedTsetlinMachine)"}


def main() -> None:
    recs = [json.loads(p.read_text()) for p in sorted(RES.glob("G*_seed*.json"))]
    recs = [r for r in recs if not r.get("smoke")]
    if not recs:
        sys.exit("no records")
    by = defaultdict(list)
    for r in recs:
        by[(r["experiment"], r["model"])].append(r)
    lines = ["# Graph TM vs Granmo et al. (arXiv:2507.14874)", "",
             "Generated by `code/graphtm/report.py` from `results/graphtm/*.json`; do not edit.", "",
             "| Experiment | Model | Paper | Ours: paper's statistic per seed (Table 3: mean of last 5 epochs ± sd over them; G0: final epoch) | "
             "Seeds | Mean over seeds ± sd | Final epoch (mean) | Within tolerance? |",
             "|---|---|---|---|---|---|---|---|"]
    for (exp, model), rs in sorted(by.items()):
        rs = sorted(rs, key=lambda r: r["seed"])
        # the paper's statistic: G0 reports the accuracy after its 4 epochs, Table 3 the mean of
        # the final 5 of 30 epochs
        key = "final_epoch" if exp == "G0" else "mean_last5"
        stat = np.array([r["summary"][key] for r in rs])
        final = np.array([r["summary"]["final_epoch"] for r in rs])
        per_seed = "; ".join(f"s{r['seed']}: {r['summary']['final_epoch']:.2f} (final)" if exp == "G0" else
                             f"s{r['seed']}: {r['summary']['mean_last5']:.2f} ± {r['summary']['sd_last5']:.2f}"
                             for r in rs)
        rep = rs[0]["reported"] or {}
        paper = rep.get("accuracy")
        paper_s = "—" if paper is None else f"{paper:.2f}" + (f" ± {rep['pm']:.2f}" if "pm" in rep else "")
        sd = float(stat.std(ddof=1)) if len(stat) > 1 else 0.0
        if paper is None:
            ok = "—"
        else:
            tol = max(1.0, 2 * sd)
            diff = float(stat.mean()) - paper
            ok = f"{'yes' if abs(diff) <= tol else 'no'} ({diff:+.2f} pp, tol {tol:.2f})"
        lines.append(f"| {NAMES.get(exp, exp)} | {MODELS[model]} | {paper_s} | {per_seed} | {len(rs)} | "
                     f"{stat.mean():.2f} ± {sd:.2f} | {final.mean():.2f} | {ok} |")
    lines += ["", "Ordering check (paper: CoTM ≥ GraphTM on MNIST and F-MNIST):", ""]
    for exp in ("G1", "G2"):
        if (exp, "graph") in by and (exp, "cotm") in by:
            g = np.mean([r["summary"]["mean_last5"] for r in by[(exp, "graph")]])
            c = np.mean([r["summary"]["mean_last5"] for r in by[(exp, "cotm")]])
            lines.append(f"* {NAMES[exp]}: CoTM {c:.2f} vs GraphTM {g:.2f}, difference {c - g:+.2f} pp "
                         f"(paper {by[(exp, 'cotm')][0]['reported']['accuracy'] - by[(exp, 'graph')][0]['reported']['accuracy']:+.2f} pp)")
    r0 = recs[0]
    state = RES / "src_state.json"
    if state.exists():
        st = json.loads(state.read_text())
        lines += ["", f"Source state of the runs: base commit `{st['base_commit']}` plus the uncommitted `src/` "
                  f"diff with sha256 `{st['src_diff_sha256'][:16]}…` (library step L1, committed afterwards; "
                  "see `src_state.json`)."]
    lines += ["", f"torchtsetlin {r0['torchtsetlin']} at `{r0['git_sha']}`; GPUs: "
              f"{'; '.join(r0['env'].get('gpus', []))}.",
              "", "Skipped (no comparable published number): CIFAR-10 (preprocessing not reconstructible: "
              "2,500 symbols), multivalue noisy XOR (curves only). See `plans/graph-tm-reproduction.md`."]
    text = "\n".join(lines) + "\n"
    (RES / "REPORT.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
