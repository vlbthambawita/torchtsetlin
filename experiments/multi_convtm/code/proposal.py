import json
import statistics as st

from common import REPORT_DIR, RESULTS


def load(name):
    p = RESULTS / name
    return json.loads(p.read_text()) if p.exists() else None


def curve(tag):
    r = load(f"{tag}.json")
    return {e["epoch"]: e for e in r["curve"]} if r else {}


def acc(tag, epoch):
    c = curve(tag)
    return c[epoch]["test_acc"] if epoch in c else None


def f(v, nd=1):
    return "pending" if v is None else f"{v:.{nd}f}"


def mean_over(tags, epoch):
    vals = [acc(t, epoch) for t in tags]
    vals = [v for v in vals if v is not None]
    return (st.mean(vals), len(vals)) if vals else (None, 0)


def sec_per_epoch(tag, last=10):
    c = curve(tag)
    if not c:
        return None
    es = sorted(c)[-last:]
    return st.mean(c[e]["train_s"] + c[e]["test_s"] for e in es)


