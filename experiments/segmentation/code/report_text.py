def _g(R, prefix, key="miou", src="val_native"):
    vals = []
    for k, r in R.items():
        if re.fullmatch(re.escape(prefix) + r"_s\d+(_r\d+)?", k) and r.get("status") == "completed":
            x = (r.get(src) or {}).get(key)
            if x is not None:
                vals.append(x)
    return float(np.mean(vals)) if vals else None


def _f(x, d=3):
    return "n/a" if x is None else f"{x:.{d}f}"


def _s(x, d=3):
    return "n/a" if x is None else f"{x:+.{d}f}"


def _iou(R, rid, arm, k):
    r = R.get(rid)
    if not r:
        return None
    return {x["arm"]: x["summary"] for x in r["rows"]}[arm]["iou"][k]


def _ci(c, d=3):
    if not c or not c.get("n_seeds"):
        return "n/a"
    return f"{c['estimate']:+.{d}f} (95% CI {c['ci95'][0]:+.{d}f} to {c['ci95'][1]:+.{d}f}, {c['n_seeds']} seeds × {c['n_groups']} groups)"


def _cmp(a, b, tol=0.005, more="higher than", less="lower than", same="indistinguishable from"):
    if a is None or b is None:
        return "not comparable with"
    return more if a - b > tol else (less if b - a > tol else same)


def _ref(R, rid, arm, key="miou"):
    r = R.get(rid)
    if not r:
        return None
    by = {x["arm"]: x["summary"] for x in r["rows"]}
    return None if arm not in by else by[arm][key] - by["raw"][key]


def _stress(R, run, name):
    r = R.get(f"STRESS_{run}_val")
    if not r:
        return None
    rows = {x["stress"]: x["summary"]["miou"] for x in r["rows"]}
    return rows[name] - rows["clean"] if name in rows else None


def _pf(R, rid):
    h = (R.get(rid) or {}).get("history") or []
    return h[-1]["pixels_fed"] if h else None


def acceptance(resk, resa):
    out = {}
    ab, bf = resk.get("AB_vs_base"), resk.get("AB_vs_base_bf1")
    if ab and ab.get("n_seeds"):
        q = ab["estimate"] >= 0.02 and ab["ci95"][0] > 0
        g = bf is None or not bf.get("n_seeds") or bf["estimate"] >= -0.01
        out["kvasir"] = (q and g, q, g)
    aa, ad = resa.get("AB_vs_base"), resa.get("AB_vs_base_fgdice")
    if aa and aa.get("n_seeds"):
        s = aa["estimate"] > 0 and aa["ci95"][0] > 0
        g = ad is None or not ad.get("n_seeds") or ad["estimate"] >= -0.01
        out["acdc"] = (s and g, s, g)
    return out


