"""Aggregate the run records into REPORT.md / REPORT_<arm>.md and results/summary.json (plan Phase 7).

Every number comes from ``results/<arm>/*.json``. Cell statistic (D7): test accuracy at the
best-validation epoch (mean ± sd when there are several seeds).

Usage: python code/report.py --arm smoke      # -> REPORT_smoke.md
       python code/report.py --arm pricing    # -> REPORT_pricing.md (cost table)
       python code/report.py --arm pilot      # -> REPORT_pilot.md + results/pilot/choice.json (--choose)
       python code/report.py                  # main (+ ablation, seeds) -> REPORT.md, results/summary.json
"""

import argparse
import glob
from collections import defaultdict

import numpy as np

from common import BASE, CELLS, CORE, PROG, RESULTS, read_json, write_json


def load(arm, kind="run"):
    return [r for r in (read_json(f) for f in sorted(glob.glob(str(RESULTS / arm / "*.json"))))
            if r.get("kind") == kind]


def usage_str(pu):
    if not pu:
        return "–"
    s = " ".join(f"{n} {100 * (p + q):.0f}" for n, p, q in zip(pu["names"], pu["pos"], pu["neg"]))
    return s + (f" pos {100 * pu['position']:.0f}" if "position" in pu else "")


def smoke_report():
    recs = load("smoke")
    chk = read_json(RESULTS / "smoke" / "encoding_checks.json") if (RESULTS / "smoke" / "encoding_checks.json").exists() else {}
    rc = read_json(RESULTS / "smoke" / "resume_check.json") if (RESULTS / "smoke" / "resume_check.json").exists() else {}
    L = ["# fmnist_bitplanes — smoke test", "",
         "Generated by `code/report.py --arm smoke` from `results/smoke/`. Not results: 1 epoch on",
         "2 000 training images (500 validation / 500 test), full-size models, RTX 3080.", "",
         "## Encoding checks", "",
         f"All pass: **{chk.get('all_pass')}**. " + ", ".join(
             f"{k} {v}" for k, v in chk.items() if isinstance(v, bool) and k != "all_pass"), "",
         f"Feature-group layout: {chk.get('feature_groups_layout')}", "",
         "Bit density per plane (share of ones, all 70 000 images):", "",
         "| Encoding | per plane |", "|---|---|"]
    for e, d in chk.get("density", {}).items():
        L.append(f"| {e} | {' '.join(f'{x:.3f}' for x in d)} |")
    L += ["", "## Resume check", "", f"`{rc}`" if rc else "missing", "",
          "## Every configuration", "",
          "| Tag | Status | Literals | Train s (63 updates) | Peak MiB | Val | Plane usage % (incl. literals) |",
          "|---|---|---|---|---|---|---|"]
    for r in sorted(recs, key=lambda r: r["tag"]):
        c = r["curve"][-1] if r["curve"] else {}
        L.append(f"| {r['tag']} | {r['status']} | {r['hp']['n_literals']} | {c.get('train_s', 0):.1f} | "
                 f"{c.get('peak_gpu_mib', 0):.0f} | {c.get('val_acc', 0):.1f} | {usage_str(c.get('plane_usage'))} |")
    failed = sorted(p.name for p in (PROG / ".cache" / "claims" / "smoke").glob("*.failed-*"))
    L += ["", f"Failed jobs: {failed or 'none'}", ""]
    (PROG / "REPORT_smoke.md").write_text("\n".join(L))
    print("\n".join(L[-40:]))


def pricing_report():
    recs = load("pricing", "calibration")
    L = ["# fmnist_bitplanes — pricing (Phase 1)", "",
         "Generated by `code/report.py --arm pricing`. Estimated from timed updates after a warm-up;",
         "an epoch = 50 000 / 32 updates + validation + test evaluation. RTX 3080.", "",
         "| Tag | Literals | ms/update | Train s/epoch | Eval s/epoch | Peak MiB | h per 100 epochs |",
         "|---|---|---|---|---|---|---|"]
    tot = 0.0
    for r in sorted(recs, key=lambda r: r["tag"]):
        ep = r["train_s_per_epoch"] + r["eval_s_per_epoch"]
        tot += ep
        L.append(f"| {r['tag']} | {r['hp']['n_literals']} | {r['ms_per_update']:.1f} | "
                 f"{r['train_s_per_epoch']:.0f} | {r['eval_s_per_epoch']:.0f} | {r['peak_gpu_mib']:.0f} | "
                 f"{ep * 100 / 3600:.1f} |")
    (PROG / "REPORT_pricing.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


def pilot_report(choose):
    recs = [r for r in load("pilot") if r.get("status") == "done"]
    by = defaultdict(list)
    for r in recs:
        by[(r["hp"]["arch"], r["hp"]["enc"])].append(r)
    L = ["# fmnist_bitplanes — pilot (Phase 3)", "",
         "Selection on **validation** accuracy only (C = 2 000, seed 0, ≤ 60 epochs); ties go to the",
         "base s. Test accuracy is shown but not used.", "",
         "| Cell | s | kd | Best val | @ epoch | Test there | Chosen |", "|---|---|---|---|---|---|---|"]
    choice = {}
    for (a, e) in CELLS:
        rs = by.get((a, e), [])
        if not rs:
            continue
        s_ref = BASE[a]["s"]
        best = max(rs, key=lambda r: (r["best_val_acc"], r["hp"]["s"] == s_ref))
        choice[f"{a}_{e}"] = {"s": best["hp"]["s"], "kd": best["hp"]["kd"], "val": best["best_val_acc"],
                              "tag": best["tag"]}
        for r in sorted(rs, key=lambda r: (r["hp"]["s"], r["hp"]["kd"] or 0)):
            L.append(f"| {a} × {e} | {r['hp']['s']:g} | {r['hp']['kd'] or '–'} | {r['best_val_acc']:.2f} | "
                     f"{r['best_epoch']} | {r['test_acc_at_best']:.2f} | {'**yes**' if r is best else ''} |")
    (PROG / "REPORT_pilot.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))
    if choose:
        write_json(choice, RESULTS / "pilot" / "choice.json")
        print("wrote results/pilot/choice.json")


def stat(v):
    v = np.asarray(v, float)
    return None if not len(v) else dict(mean=float(v.mean()), sd=float(v.std(ddof=1)) if len(v) > 1 else 0.0,
                                        n=int(len(v)))


def main_report():
    recs = [r for arm in ("main", "seeds") for r in load(arm) if r.get("status") == "done"]
    by = defaultdict(list)
    for r in recs:
        h = r["hp"]
        by[(h["arch"], h["enc"], h["clauses_per_class"])].append(r)
    L = ["# fmnist_bitplanes — results", "",
         "Generated by `code/report.py` from `results/main` and `results/seeds`. Statistic: test accuracy at",
         "the best-validation epoch. Core cells in bold. RTX 3080.", "",
         "| Cell | C/class | Test @ best | n | Best epoch | s/epoch | Time to best h | Literals | Plane usage % |",
         "|---|---|---|---|---|---|---|---|---|"]
    summary = {}
    for (a, e) in CELLS:
        for c in (2000, 8000):
            rs = by.get((a, e, c))
            if not rs:
                continue
            st = stat([r["test_acc_at_best"] for r in rs])
            r0 = rs[0]
            name = f"{a} × {e}"
            name = f"**{name}**" if (a, e) in CORE else name
            L.append(f"| {name} | {c} | {st['mean']:.2f}" + (f" ± {st['sd']:.2f}" if st["n"] > 1 else "") +
                     f" | {st['n']} | {np.mean([r['best_epoch'] for r in rs]):.0f} | "
                     f"{np.mean([r['train_s_per_epoch_mean'] for r in rs]):.1f} | "
                     f"{np.mean([r['gpu_s_to_best'] for r in rs]) / 3600:.2f} | {r0['hp']['n_literals']} | "
                     f"{usage_str(r0.get('plane_usage_at_best'))} |")
            summary[f"{a}_{e}_c{c}"] = dict(test_acc_at_best=st, tags=[r["tag"] for r in rs])
    (PROG / "REPORT.md").write_text("\n".join(L) + "\n")
    write_json(summary, RESULTS / "summary.json")
    print("\n".join(L))


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--arm", default="main", choices=["smoke", "pricing", "pilot", "main"])
    ap.add_argument("--choose", action="store_true", help="pilot: write results/pilot/choice.json")
    a = ap.parse_args()
    {"smoke": smoke_report, "pricing": pricing_report, "main": main_report}.get(
        a.arm, lambda: pilot_report(a.choose))()
