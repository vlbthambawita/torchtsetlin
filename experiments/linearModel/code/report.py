"""Phase 8: ``report/REPORT.md`` + figures, generated from ``results/**/*.json`` only (rule C2).

    python -m experiments.linearModel.code.report
"""

from __future__ import annotations

import json
from collections import defaultdict

import numpy as np

from .data import EXP
from .main_grid import CONFIGS, RESULTS

REPORT = EXP / "report"
FIG = REPORT / "figures"
ARMS = ["A0", "A1", "A1c", "A3", "A3L", "A4", "A4q", "A5", "A2", "A2c"]
ARM_NAME = {"A0": "source TM", "A1": "gates + constants (int)", "A1c": "gates + constants (ridge)",
            "A3": "gates + affine (int) — proposed", "A3L": "A3, line search", "A4": "gates + affine (ridge)",
            "A4q": "A4 rounded to grid", "A5": "random gates + affine (int)", "A2": "global linear (int)",
            "A2c": "global linear (ridge)"}
# reference palette slots (dataviz skill, light mode): blue, orange, aqua; gray for references
C_FLAT, C_CONV, C_THIRD, C_REF = "#2a78d6", "#eb6834", "#1baf7a", "#8a8984"


def load(dirname):
    return [json.loads(p.read_text()) for p in sorted((RESULTS / dirname).glob("*.json"))]


def fam_M_seed(group):
    parts = group.split("_")
    fam = parts[0]
    M = int(parts[1][1:]) if parts[1].startswith("M") else 0
    seed = int([p for p in parts if p.startswith("seed")][0][4:])
    return fam, M, seed


def fmt(x, nd=4):
    return "–" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:.{nd}f}"


def pm(xs, nd=4, scale=1.0):
    xs = [x * scale for x in xs]
    if not xs:
        return "–"
    if len(xs) == 1:
        return f"{xs[0]:.{nd}f} (n=1)"
    return f"{np.mean(xs):.{nd}f} ± {np.std(xs, ddof=1):.{nd}f} (n={len(xs)})"


def main():
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    FIG.mkdir(parents=True, exist_ok=True)
    main_recs = load("main")
    src = {r["source_id"]: r for r in load("source")}
    tests = {r["run_id"]: r for r in load("test")} if (RESULTS / "test").exists() else {}
    final = json.loads((CONFIGS / "final.json").read_text()) if (CONFIGS / "final.json").exists() else []
    sel = {(o["family"], o["M"], o["arm"]): o for o in final}
    L = []
    w = L.append
    w("# Boolean-gated linear outputs for Tsetlin machines — MNIST results\n")
    w("Generated by `code/report.py` from `results/**/*.json` (rule C2); do not hand-edit. "
      "Plan: `PLAN.md`; decisions and deviations: `DECISIONS.md`.\n")

    # ------------------------------------------------------------------ sources
    w("## 1. Source models (A0)\n")
    w("Seed-0 grid selection by validation accuracy (ties → earlier epoch / smaller `T`, `s`). "
      "Flat: unweighted `TsetlinMachine`; conv: weighted `ConvTsetlinMachine` 10×10 patches, "
      "position encoding (D10). `Binarizer(0.5)`, batch 32, ≤ 30 epochs, 50k/10k split.\n")
    w("| kind | M | T | s | best epoch | val acc seed 0 | val acc seeds 0–2 | fit s (seed 0) | included literals |")
    w("|---|---|---|---|---|---|---|---|---|")
    from .sources import selected
    for kind, Ms in (("flat", (2, 10, 20, 50, 100, 500)), ("conv", (2, 10, 20, 200))):
        for M in Ms:
            r = selected(kind, M)
            if r is None:
                continue
            accs = [s["val_acc"] for s in src.values() if s["kind"] == kind and s["M"] == M and s["T"] == r["T"]
                    and s["s"] == r["s"] and s["threshold"] == 0.5 and s["weighted"] == r["weighted"]
                    and s["manifest"] == "split_seed0"]
            w(f"| {kind} | {M} | {r['T']:g} | {r['s']:g} | {r['best_epoch']} | {r['val_acc']:.4f} | {pm(accs)} | "
              f"{r['fit_seconds']:.0f} | {r['n_included_literals']} |")
    w("")

    # ------------------------------------------------------------------ seed-0 validation, selected configs
    w("## 2. Validation accuracy, seed 0, each arm at its selected configuration\n")
    w("Selection key: spec §10.1 `(-accuracy, MSE)` on validation; ties → earlier grid point. "
      "A5 is shown at the A3-selected configuration (mean of 3 random-gate draws). "
      "A2/A2c have no gates (same for every row).\n")
    fams = [("flat", (2, 10, 20)), ("conv", (2, 10, 20))]
    hdr = ["kind", "M"] + ARMS
    w("| " + " | ".join(hdr) + " |")
    w("|" + "---|" * len(hdr))
    for fam, Ms in fams:
        for M in Ms:
            row = [fam, str(M)]
            for a in ARMS:
                if a == "A5":
                    v = [o["val_acc"] for (f, m, aa), o in sel.items() if f.startswith("rand") and m == M and aa == "A5"]
                    row.append(fmt(np.mean(v)) if v and fam == "flat" else "–")
                elif a in ("A2", "A2c"):
                    o = sel.get(("global", 0, a))
                    row.append(fmt(o["val_acc"]) if o else "–")
                else:
                    o = sel.get((fam, M, a))
                    row.append(fmt(o["val_acc"]) if o else "–")
            w("| " + " | ".join(row) + " |")
    w("")
    w("Selected hyperparameters (`lambda`, `delta`, `Q`):\n")
    w("| kind | M | arm | lambda | delta | Q |")
    w("|---|---|---|---|---|---|")
    for (f, M, a), o in sorted(sel.items()):
        c = o["config"]
        if c is not None and not f.startswith("rand"):
            w(f"| {f} | {M} | {a} | {c.get('lam')} | {c.get('delta', '–')} | {c.get('Q', '–')} |")
    w("")

    # ------------------------------------------------------------------ test
    by_cell = defaultdict(list)              # (fam, M, arm) -> list of (seed, test acc, run)
    for r in main_recs:
        t = tests.get(r["run_id"])
        if t is None:
            continue
        fam, M, seed = fam_M_seed(r["group"])
        if r["group"].endswith("_ref"):
            fam = fam + "_ref"
        key = ("flat" if fam.startswith("rand") else fam, M, r["arm"])
        by_cell[key].append((seed, t["test"]["acc"], r))
    if by_cell:
        w("## 3. Test accuracy (official 10k test set, one pass per frozen run)\n")
        w("Mean ± SD over source seeds 0–2 (A5: over seeds × 3 draws). `configs/final.json` frozen before the "
          "first test access; every access is in `results/test_access_log.jsonl`.\n")
        w("| kind | M | " + " | ".join(ARMS) + " |")
        w("|---|---|" + "---|" * len(ARMS))
        for fam, Ms in fams + [("thr03", (20,))]:
            for M in Ms:
                row = [fam, str(M)]
                for a in ARMS:
                    if a in ("A2", "A2c"):
                        v = by_cell.get(("global", 0, a), [])
                    else:
                        v = by_cell.get((fam, M, a), [])
                    row.append(pm([x[1] for x in v]) if v else "–")
                w("| " + " | ".join(row) + " |")
        w("")
        w("Reference source models (A0 only):\n")
        w("| kind | M | test acc |")
        w("|---|---|---|")
        for (fam, M, _a), v in sorted(by_cell.items()):
            if fam.endswith("_ref"):
                w(f"| {fam[:-4]} | {M} | {pm([x[1] for x in v])} |")
        w("")

        # paired differences + preregistered decision rules
        w("### 3.1 Preregistered comparisons (PLAN §7)\n")
        w("**Supported** = same sign for all 3 seeds **and** |mean| > 0.5 percentage points. "
          "Differences in percentage points (pp), paired by source seed.\n")
        w("| question | kind | M | comparison | per-seed diff (pp) | mean (pp) | verdict |")
        w("|---|---|---|---|---|---|---|")

        def seedmap(fam, M, a):
            if a in ("A2", "A2c"):
                v = by_cell.get(("global", 0, a), [])
            else:
                v = by_cell.get((fam, M, a), [])
            d = defaultdict(list)
            for s, acc, _ in v:
                d[s].append(acc)
            return {s: float(np.mean(x)) for s, x in d.items()}

        comps = [("Q1 slopes help", "A3", "A1"), ("Q2 beats source", "A3", "A0"), ("Q3 gates help (int)", "A3", "A2"),
                 ("Q3 gates help (ridge)", "A3", "A2c"), ("Q4 quantization cost", "A4", "A3"),
                 ("Q5 learned gates matter", "A3", "A5"), ("diag: optimizer gap", "A4q", "A3"),
                 ("diag: rounding gap", "A4", "A4q")]
        for fam, Ms in fams:
            for M in Ms:
                for q, a, b in comps:
                    if b == "A5" and fam != "flat":
                        continue
                    ma, mb = seedmap(fam, M, a), seedmap(fam, M, b)
                    seeds = sorted(set(ma) & set(mb))
                    if not seeds:
                        continue
                    d = [100 * (ma[s] - mb[s]) for s in seeds]
                    mean = float(np.mean(d))
                    if q.startswith("Q4"):
                        verdict = "small (≤ 0.5 pp)" if mean <= 0.5 else "not small"
                    elif q.startswith("diag"):
                        verdict = "diagnostic"
                    else:
                        same = all(x > 0 for x in d) or all(x < 0 for x in d)
                        verdict = ("supported " + ("positive" if mean > 0 else "negative")) if (
                            len(seeds) == 3 and same and abs(mean) > 0.5) else "not supported at this budget"
                    w(f"| {q} | {fam} | {M} | {a} − {b} | {', '.join(f'{x:+.2f}' for x in d)} | {mean:+.2f} | {verdict} |")
        w("")

    # ------------------------------------------------------------------ optimisation diagnostics
    w("## 4. Optimisation diagnostics (seed 0, selected A3 / A3-L)\n")
    w("| kind | M | arm | delta | lambda | stop | sweeps | best sweep | nonzero | at ±Q | terminal improving coords | "
      "selected improving coords | train J (int) | train J (A4 same λ) | fit s |")
    w("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    recs_by_id = {r["run_id"]: r for r in main_recs}
    for fam, Ms in fams:
        for M in Ms:
            for a in ("A3", "A3L"):
                o = sel.get((fam, M, a))
                if not o:
                    continue
                r = recs_by_id[o["run_id"]]
                c = r["config"]
                a4 = [x for x in main_recs if x["group"] == r["group"] and x["arm"] == "A4" and x["config"]["lam"] == c["lam"]]
                w(f"| {fam} | {M} | {a} | {c['delta']:g} | {c['lam']:g} | {r['stop_reason']} | {r['terminal_sweep']} | "
                  f"{r['best_sweep']} | {r['frac_nonzero']:.3f} | {r['frac_at_bound']:.4f} | "
                  f"{r['terminal_audit']['improving_coordinate_count']} | {r['selected_audit']['improving_coordinate_count']} | "
                  f"{r['trace'][-1]['J']:.5f} | {fmt(a4[0]['train_J'], 5) if a4 else '–'} | {r['timings']['total']:.0f} |")
    w("")
    w("Every integer-search run in the main grid, by stop reason:\n")
    stops = defaultdict(int)
    for r in main_recs:
        if "stop_reason" in r:
            stops[(r["arm"], r["stop_reason"])] += 1
    w("| arm | stop reason | runs |")
    w("|---|---|---|")
    for (a, s), n in sorted(stops.items()):
        w(f"| {a} | {s} | {n} |")
    w("")

    # ------------------------------------------------------------------ gate coverage
    w("## 5. Gate coverage (training set)\n")
    w("Mean number of active gates per example in a class bank, and clauses that never fire.\n")
    w("| kind | M | mean active / bank / example | never-active clauses | mean activation rate |")
    w("|---|---|---|---|---|")
    for fam, Ms in fams + [("rand0", (2, 10, 20))]:
        for M in Ms:
            rs = [r for r in main_recs if r["group"] == f"{fam}_M{M}_seed0" and "gate_stats" in r]
            if rs:
                g = rs[0]["gate_stats"]["train"]
                w(f"| {fam} | {M} | {g['mean_active_per_example'] / 10:.3f} | {g['n_never_active']} | {g['mean_activation']:.3f} |")
    w("")

    # ------------------------------------------------------------------ cost
    w("## 6. Cost (seed 0, selected configurations)\n")
    w("Hardware: RTX 3090 / 3080, 32 CPU cores shared between concurrent jobs, so times are indicative. "
      "Inference = gate evaluation + scores on the 10k validation set, CPU, after reload from disk.\n")
    w("| kind | M | arm | coefficients | serialized bytes | Gram build s | optimise s | inference s (10k) | peak RSS GB |")
    w("|---|---|---|---|---|---|---|---|---|")
    for fam, Ms in fams:
        for M in Ms:
            for a in ("A0", "A1", "A3", "A3L", "A4"):
                o = sel.get((fam, M, a))
                if not o:
                    continue
                r = recs_by_id[o["run_id"]]
                if a == "A0":
                    w(f"| {fam} | {M} | A0 | {r['sizes']['n_clauses']} clauses / {r['sizes']['n_included_literals']} literals | – | – | "
                      f"{r['source_record'].get('fit_seconds', 0):.0f} (TM training) | {r['inference_seconds_val']:.2f} (GPU) | – |")
                    continue
                sz = r.get("sizes", {})
                w(f"| {fam} | {M} | {a} | {sz.get('n_coefficients', '–')} | {sz.get('serialized_bytes', '–')} | "
                  f"{r['timings'].get('gram_build', 0):.0f} | {r['timings'].get('optimize', r['timings'].get('ridge', 0)):.0f} | "
                  f"{fmt(r.get('inference_seconds_val'), 2)} | {r['peak_rss_gb']:.1f} |")
    w("")

    # ------------------------------------------------------------------ figures
    figs = []
    # (a) validation accuracy vs M per arm
    fig, axes = plt.subplots(1, 2, figsize=(10, 3.8), sharey=True)
    for ax, (fam, Ms) in zip(axes, fams):
        for a, col, ls in (("A0", C_REF, "--"), ("A1", C_THIRD, "-"), ("A3", C_FLAT, "-"), ("A4", C_CONV, ":")):
            ys = [sel.get((fam, M, a), {}).get("val_acc", np.nan) for M in Ms]
            ax.plot(Ms, ys, ls, color=col, lw=2, marker="o", ms=8, label=f"{a}: {ARM_NAME[a]}")
        g = sel.get(("global", 0, "A2"))
        if g:
            ax.axhline(g["val_acc"], color="#52514e", lw=1, ls="-.", label="A2: global linear (int)")
        ax.set_title(f"{fam} gates", loc="left")
        ax.set_xlabel("clauses per class M")
        ax.set_xscale("log", base=2)
        ax.set_xticks(Ms, [str(m) for m in Ms])
        ax.grid(alpha=0.25, lw=0.5)
        for s in ("top", "right"):
            ax.spines[s].set_visible(False)
    axes[0].set_ylabel("validation accuracy (seed 0)")
    axes[1].legend(frameon=False, fontsize=8, loc="lower right")
    fig.tight_layout()
    fig.savefig(FIG / "val_acc_vs_M.png", dpi=150)
    plt.close(fig)
    figs.append(("val_acc_vs_M.png", "Validation accuracy (seed 0, selected configuration) vs clauses per class."))

    # (b) objective vs sweep for selected A3 runs
    fig, ax = plt.subplots(figsize=(6, 3.6))
    for fam, col in (("flat", C_FLAT), ("conv", C_CONV)):
        for M, lsty in zip((2, 10, 20), (":", "--", "-")):
            o = sel.get((fam, M, "A3"))
            if o:
                tr = recs_by_id[o["run_id"]]["trace"]
                ax.plot([t["sweep"] for t in tr], [t["J"] for t in tr], lsty, color=col, lw=2, label=f"{fam} M={M}")
    ax.set_xlabel("sweep")
    ax.set_ylabel("training objective J")
    ax.set_yscale("log")
    ax.grid(alpha=0.25, lw=0.5)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    ax.legend(frameon=False, fontsize=8, ncol=2)
    fig.tight_layout()
    fig.savefig(FIG / "objective_vs_sweep.png", dpi=150)
    plt.close(fig)
    figs.append(("objective_vs_sweep.png", "Training objective per sweep for the selected A3 runs (seed 0)."))

    # (c) slope maps of the most active clauses (selected A3, M = 20)
    from .hybrid import HybridModel
    for fam in ("flat", "conv"):
        o = sel.get((fam, 20, "A3"))
        if not o:
            continue
        r = recs_by_id[o["run_id"]]
        m = HybridModel.load(EXP / r["sizes"]["artifact"])
        rate = np.asarray(r["gate_stats"]["train"]["activation_rate"]).reshape(10, -1)
        _, bias, W = m.layout.split(m.states.astype(float) * m.cfg.delta)
        fig, axes = plt.subplots(2, 10, figsize=(14, 3.4))
        vmax = np.abs(W).max() or 1.0
        for k in range(10):
            top = np.argsort(-rate[k])[:2]
            for i, j in enumerate(top):
                ax = axes[i, k]
                ax.imshow(W[k, j].reshape(28, 28), cmap="RdBu_r", vmin=-vmax, vmax=vmax)
                ax.set_xticks([])
                ax.set_yticks([])
                ax.set_title(f"{k}/c{j} r={rate[k, j]:.2f}", fontsize=7)
        fig.suptitle(f"A3 slope maps w_kj (28×28), {fam} gates M=20: two most active clauses per class; "
                     f"red > 0, blue < 0, |max| = {vmax:.3f}", fontsize=9)
        fig.tight_layout()
        fig.savefig(FIG / f"slope_maps_{fam}_M20.png", dpi=130)
        plt.close(fig)
        figs.append((f"slope_maps_{fam}_M20.png", f"Learned slope maps, {fam} gates, M = 20 (seed 0)."))

    w("## 7. Figures\n")
    for f, cap in figs:
        w(f"![{cap}](figures/{f})\n\n*{cap}*\n")
    (REPORT / "REPORT.md").write_text("\n".join(L))
    print(f"wrote {REPORT / 'REPORT.md'} ({len(L)} lines), {len(figs)} figures")


if __name__ == "__main__":
    main()
