def tex_escape(s: str) -> str:
    return s.replace("_", r"\_").replace("&", r"\&").replace("%", r"\%")


def fmt(v, nd=3, sign=False) -> str:
    if v is None or (isinstance(v, float) and np.isnan(v)):
        return "--"
    return f"{v:+.{nd}f}" if sign else f"{v:.{nd}f}"


def pval(p: float) -> str:
    if p is None or np.isnan(p):
        return "--"
    if p < 0.001:
        m, e = f"{p:.1e}".split("e")
        return f"\\ensuremath{{{m}\\times 10^{{{int(e)}}}}}"
    return f"{p:.3f}"


_DIG = dict(zip("0123456789", ["Zero", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine"]))


def mname(s: str) -> str:
    """A valid LaTeX control-word name: letters only (digits spelled out)."""
    return "".join(_DIG.get(ch, ch) for ch in s if ch.isalnum())


class Macros:
    def __init__(self):
        self.lines: List[str] = []

    def add(self, name: str, value: str) -> None:
        self.lines.append(f"\\newcommand{{\\{mname(name)}}}{{{value}}}")

    def write(self, path: Path) -> None:
        path.write_text("% generated by code/latex_report.py -- do not edit\n" + "\n".join(self.lines) + "\n")


def _mean_table(df: pd.DataFrame, col: str = "test_auroc") -> pd.DataFrame:
    return df.groupby(["dataset_id", "dataset", "arm"])[col].mean().unstack("arm")


def _pairs(mean: pd.DataFrame, pairs=PAIRS):
    rows = []
    for a, b, q in pairs:
        if a not in mean or b not in mean:
            continue
        d = (mean[a] - mean[b]).dropna()
        if len(d) < 2:
            continue
        p = stats.wilcoxon(d.values).pvalue if np.any(d.values != 0) else 1.0
        g = np.random.default_rng(0)
        boot = d.values[g.integers(len(d), size=(10000, len(d)))].mean(1)
        lo, hi = np.percentile(boot, [2.5, 97.5])
        rows.append({"q": q, "a": a, "b": b, "n": len(d), "mean": d.mean(), "lo": lo, "hi": hi,
                     "median": d.median(), "wins": int((d > 0).sum()), "losses": int((d < 0).sum()), "p": p})
    if rows:
        ps = np.array([r["p"] for r in rows])
        order, running = np.argsort(ps), 0.0
        for i, j in enumerate(order):
            running = max(running, min(1.0, (len(ps) - i) * ps[j]))
            rows[j]["holm"] = running
    return rows


def _ranks(mean: pd.DataFrame, arms: List[str]):
    m = mean[[a for a in arms if a in mean]].dropna(axis=0, how="any")
    if m.shape[0] < 2:
        return None, None, None
    rk = m.rank(axis=1, ascending=False).mean()
    k, n = m.shape[1], m.shape[0]
    fr = stats.friedmanchisquare(*[m[c].values for c in m.columns])
    cd = stats.studentized_range.ppf(0.95, k, np.inf) / np.sqrt(2) * np.sqrt(k * (k + 1) / (6.0 * n))
    return rk, fr, (cd, n, k)


def pending(path: Path, what: str) -> None:
    path.write_text(f"\\begin{{center}}\\emph{{{tex_escape(what)}: no records yet (pending).}}\\end{{center}}\n")


