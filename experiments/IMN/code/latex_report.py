def table_auroc(df: pd.DataFrame, path: Path, arms: List[str], paper: Optional[dict], caption_note: str = "") -> None:
    mean = _mean_table(df)
    std = df.groupby(["dataset_id", "dataset", "arm"]).test_auroc.std().unstack("arm")
    arms = [a for a in arms if a in mean]
    cols = "l" + "c" * len(arms) + ("c" if paper else "")
    head = " & ".join(["Dataset"] + [NAMES[a] for a in arms] + (["Paper IMN"] if paper else []))
    lines = [r"\begin{tabular}{" + cols + "}", r"\toprule", head + r" \\", r"\midrule"]
    for (did, name), r in mean.iterrows():
        best = np.nanmax(r[arms].values)
        cells = []
        for a in arms:
            v = r[a]
            if np.isnan(v):
                cells.append("--")
                continue
            s = std.loc[(did, name), a]
            c = f"{v:.3f}" + (r"{\tiny$\pm$" + f"{s:.3f}" + "}" if not np.isnan(s) else "")
            cells.append(r"\textbf{" + c + "}" if np.isclose(v, best) else c)
        ref = []
        if paper:
            pv = paper.get(str(did), {}).get("imn")
            ref = [f"{pv:.3f}" if pv is not None else "--"]
        lines.append(" & ".join([tex_escape(name)] + cells + ref) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    path.write_text("\n".join(lines) + "\n")


def table_pairs(rows, path: Path) -> None:
    lines = [r"\begin{tabular}{llrcccc}", r"\toprule",
             r"Q & Comparison $A$ vs.\ $B$ & mean $A{-}B$ & 95\% bootstrap CI & W/L & $p$ & $p_\text{Holm}$ \\",
             r"\midrule"]
    for r in rows:
        star = r"$^\ast$" if r.get("holm", 1) < 0.05 else ""
        lines.append(f"{r['q']} & {NAMES[r['a']]} vs.\\ {NAMES[r['b']]} & {r['mean']:+.4f} & "
                     f"[{r['lo']:+.4f}, {r['hi']:+.4f}] & {r['wins']}/{r['losses']} & {pval(r['p'])} & "
                     f"{pval(r['holm'])}{star} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    path.write_text("\n".join(lines) + "\n")


def table_ranks(cols: Dict[str, pd.Series], path: Path, arms: List[str]) -> None:
    names = list(cols)
    lines = [r"\begin{tabular}{l" + "c" * len(names) + "}", r"\toprule",
             " & ".join(["Method"] + names) + r" \\", r"\midrule"]
    for a in arms:
        if not any(a in s.index for s in cols.values()):
            continue
        lines.append(" & ".join([NAMES[a]] + [fmt(s.get(a, np.nan), 2) for s in cols.values()]) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    path.write_text("\n".join(lines) + "\n")


def table_interp(df: pd.DataFrame, path: Path) -> None:
    cols = [("x_linear_terms_90", "lin.\\ terms", 1), ("x_clause_terms_90", "clause terms", 1),
            ("x_active_clauses_mean", "active clauses", 1), ("x_active_clause_len_mean", "literals/clause", 1),
            ("x_local_vs_full_removal_corr", "self-consist.", 3), ("x_local_acc_k10", "fid.\\ $k{=}10$", 3),
            ("x_local_acc_k50", "fid.\\ $k{=}50$", 3)]
    cols = [c for c in cols if c[0] in df]
    agg = df.groupby("arm")[[c[0] for c in cols]].mean()
    lines = [r"\begin{tabular}{l" + "c" * len(cols) + "}", r"\toprule",
             " & ".join(["Method"] + [c[1] for c in cols]) + r" \\", r"\midrule"]
    for a in LOCAL_ARMS:
        if a in agg.index:
            lines.append(" & ".join([NAMES[a]] + [fmt(agg.loc[a, c], nd) for c, _, nd in cols]) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    path.write_text("\n".join(lines) + "\n")


