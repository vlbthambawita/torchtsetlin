def _stage_complete(stage: str) -> bool:
    """True when every queued job of ``stage`` has a record (ok or skipped). Partial stages are
    reported as pending rather than summarised on a subset of datasets."""
    jobs = set()
    for f in (EXP_DIR / "jobs").glob("*.jsonl"):
        for line in f.read_text().splitlines():
            if line.strip():
                j = json.loads(line)
                if j["stage"] == stage:
                    jobs.add((str(j["dataset"]), j["arm"], j["seed"], j.get("tag", "")))
    if not jobs:
        return True
    n = sum(1 for _ in (RESULTS / stage).glob("*/*__s*.json"))
    if n < len(jobs):
        print(f"stage {stage}: {n}/{len(jobs)} records -> pending")
    return n >= len(jobs)


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    FIG.mkdir(parents=True, exist_ok=True)
    M = Macros()
    paper = json.loads((EXP_DIR / "reference" / "paper_tables.json").read_text())["table8_default_hp"]
    stages = {s: load(s, None if s in ("abl", "reg") else "") for s in ("main", "hpo_final", "tier2", "xai", "abl", "reg")
              if (RESULTS / s).exists()}
    stages = {k: v for k, v in stages.items() if not v.empty and _stage_complete(k)}
    rank_cols: Dict[str, pd.Series] = {}

    # ---- Phase 2 / 3 / 6 accuracy
    for st, label, paper_col in (("main", "Main", True), ("hpo_final", "Hpo", True), ("tier2", "Tiertwo", True)):
        tag = label
        if st not in stages:
            for f in ("auroc_a", "auroc_b", "pairs", "interp"):
                pending(OUT / f"{st}_{f}.tex", f"stage {st}")
            M.add(f"{tag}Status", "pending")
            continue
        df = stages[st]
        M.add(f"{tag}Status", "complete")
        M.add(f"{tag}Records", str(len(df)))
        M.add(f"{tag}Datasets", str(df.dataset_id.nunique()))
        M.add(f"{tag}Seeds", str(df.seed.nunique()))
        table_auroc(df, OUT / f"{st}_auroc_a.tex", ["lr", "dt", "rf", "gbdt", "tabresnet", "imn"], None)
        table_auroc(df, OUT / f"{st}_auroc_b.tex", ["imn", "tm", "clause_lr", "imn_tm", "imn_tm_rand", "imn_hybrid",
                                                    "tm_gated"], paper if paper_col else None)
        mean = _mean_table(df).droplevel(1)
        rows = _pairs(mean)
        table_pairs(rows, OUT / f"{st}_pairs.tex")
        for r in rows:
            key = f"{tag}{r['a']}{r['b']}".replace("_", "")
            key = "".join(ch for ch in key if ch.isalpha())
            M.add(key + "Mean", f"{r['mean']:+.4f}")
            M.add(key + "Lo", f"{r['lo']:+.4f}")
            M.add(key + "Hi", f"{r['hi']:+.4f}")
            M.add(key + "Wins", str(r["wins"]))
            M.add(key + "Losses", str(r["losses"]))
            M.add(key + "Holm", pval(r["holm"]))
        rk, fr, cdinfo = _ranks(mean, MAIN_ARMS)
        if rk is not None:
            rank_cols[{"main": "default", "hpo_final": "tuned", "tier2": "Tier 2"}[st]] = rk
            M.add(f"{tag}FriedmanP", pval(fr.pvalue))
            M.add(f"{tag}FriedmanChi", f"{fr.statistic:.1f}")
            M.add(f"{tag}CD", f"{cdinfo[0]:.2f}")
            M.add(f"{tag}RankN", str(cdinfo[1]))
            for a in MAIN_ARMS:
                if a in rk:
                    M.add(f"{tag}Rank" + "".join(ch for ch in a if ch.isalpha()), f"{rk[a]:.2f}")
        r = fig_gap(df, FIG / f"{st}_gap.pdf", {"main": "Default hyper-parameters", "hpo_final": "Tuned",
                                                 "tier2": "Tier 2"}[st])
        if r is not None:
            M.add(f"{tag}GapCorr", f"{r:.2f}")
        fig_delta_dots(df, FIG / f"{st}_delta.pdf")
        table_interp(df, OUT / f"{st}_interp.tex")
        agg = df.groupby("arm").mean(numeric_only=True)
        for a in LOCAL_ARMS:
            if a in agg.index:
                key = "".join(ch for ch in a if ch.isalpha())
                for c, n in (("x_local_acc_k10", "Fid"), ("x_clause_terms_90", "Clauses"),
                             ("x_linear_terms_90", "Lin"), ("x_local_vs_full_removal_corr", "Self")):
                    if c in agg and not np.isnan(agg.loc[a, c]):
                        M.add(f"{tag}{n}{key}", f"{agg.loc[a, c]:.0f}" if n in ("Clauses", "Lin") else f"{agg.loc[a, c]:.2f}")
        cost = df.groupby("arm").train_time.median()
        for a in ("imn", "imn_tm", "tm_gated", "tm"):
            if a in cost:
                M.add(f"{tag}Time" + "".join(ch for ch in a if ch.isalpha()), f"{cost[a]:.0f}")
        if st == "main":
            fig_interp(df, FIG / "main_interp.pdf")
            imn_gap = {name: (mean.loc[did, "imn"] - paper[str(did)]["imn"])
                       for did, name in df.groupby("dataset_id").dataset.first().items()
                       if str(did) in paper and paper[str(did)].get("imn") is not None}
            worst = sorted(imn_gap.items(), key=lambda kv: kv[1])[:2]
            M.add("MainWorstPaperGap", ", ".join(f"{tex_escape(n)} ({v:+.3f})" for n, v in worst))
        if st == "tier2":
            # is the IMN-TM gain explained by an under-trained IMN (step cap, D24)?
            names = df.groupby("dataset_id").dataset.first()
            pg = pd.Series({did: mean.loc[did, "imn"] - paper[str(did)]["imn"] for did in mean.index
                            if str(did) in paper and paper[str(did)].get("imn") is not None})
            g = (mean["imn_tm"] - mean["imn"]).reindex(pg.index)
            M.add("TiertwoPaperGapCorr", f"{np.corrcoef(pg.values, g.values)[0, 1]:.2f}")
            short = pg[pg < -0.03].sort_values()
            M.add("TiertwoShortN", str(len(short)))
            M.add("TiertwoShortList", ", ".join(f"{tex_escape(names[i])} ({v:+.3f})" for i, v in short.items()))
            rest = g.drop(short.index)
            M.add("TiertwoRestN", str(len(rest)))
            M.add("TiertwoRestMean", f"{rest.mean():+.4f}")
            M.add("TiertwoRestWins", str(int((rest > 0).sum())))
            M.add("TiertwoRestLosses", str(int((rest < 0).sum())))
            M.add("TiertwoRestP", pval(stats.wilcoxon(rest.values).pvalue))
            M.add("TiertwoShortMean", f"{g[short.index].mean():+.4f}")
            ep = {}
            for f in (RESULTS / "tier2").glob("*/imn__s*.json"):
                j = json.loads(f.read_text())
                ep.setdefault(j["dataset"], []).append(j.get("info", {}).get("epochs", 500))
            capped = sorted(k for k, v in ep.items() if min(v) < 500)
            M.add("TiertwoCappedN", str(len(capped)))
            M.add("TiertwoShortCapped", str(sum(names[i] in capped for i in short.index)))
        if st == "hpo_final" and "main" in stages:
            # tuning effect: tuned minus default, per arm (mean over datasets) and per dataset
            dm = _mean_table(stages["main"]).droplevel(1)
            dt = (mean - dm.reindex(index=mean.index, columns=mean.columns))
            for a in dt.columns:
                k = "".join(ch for ch in a if ch.isalpha())
                M.add(f"Tune{k}Mean", f"{dt[a].mean():+.4f}")
                M.add(f"Tune{k}Wins", str(int((dt[a] > 0).sum())))
                M.add(f"Tune{k}Auroc", f"{mean[a].mean():.4f}")
                M.add(f"Default{k}Auroc", f"{dm[a].mean():.4f}")
            names = df.groupby("dataset_id").dataset.first()
            for a in ("imn", "imn_tm"):
                k = "".join(ch for ch in a if ch.isalpha())
                lo, hi = dt[a].idxmin(), dt[a].idxmax()
                M.add(f"Tune{k}Worst", f"{tex_escape(names[lo])} ({dt[a][lo]:+.3f})")
                M.add(f"Tune{k}Best", f"{tex_escape(names[hi])} ({dt[a][hi]:+.3f}), "
                      f"{tex_escape(names[dt[a].drop(hi).idxmax()])} ({dt[a].drop(hi).max():+.3f})")
            g = (mean["imn_tm"] - mean["imn"]).sort_values()
            M.add("HpoImntmImnWorst", f"{tex_escape(names[g.index[0]])} ({g.iloc[0]:+.3f})")
            M.add("HpoImntmImnBest", f"{tex_escape(names[g.index[-1]])} ({g.iloc[-1]:+.3f})")
            M.add("HpoImntmImnMeanNoBest", f"{g.iloc[:-1].mean():+.4f}")
    if rank_cols:
        table_ranks(rank_cols, OUT / "ranks.tex", MAIN_ARMS)
        fig_ranks(rank_cols, FIG / "ranks.pdf", MAIN_ARMS)
    else:
        pending(OUT / "ranks.tex", "ranks")

    # ---- Phase 1
    sel = RESULTS / "reg" / "selection.json"
    if sel.exists():
        s = json.loads(sel.read_text())
        M.add("RegMode", s["imn_tm"]["l1_mode"])
        M.add("RegLambda", f"{s['imn_tm']['weight_norm']:g}")
        M.add("RegValid", f"{s['imn_tm']['valid_auroc']:.4f}")
    if "reg" in stages:
        r = stages["reg"]
        r["setting"] = r.get("tag", "")
        rows = []
        for p in (RESULTS / "reg").glob("*/*__s*.json"):
            j = json.loads(p.read_text())
            rows.append({"arm": j["arm"], "tag": j["tag"], "dataset": j["dataset"],
                         "valid": j["metrics"]["valid"]["auroc"], "train": j["metrics"]["train"]["auroc"]})
        rr = pd.DataFrame(rows).groupby(["arm", "tag", "dataset"]).mean(numeric_only=True).groupby(["arm", "tag"]).mean()
        tab = rr.valid.unstack("arm")
        lines = [r"\begin{tabular}{lcc}", r"\toprule", r"$\ell_1$ mode, $\lambda$ & IMN-TM & IMN-Hybrid \\",
                 r"\midrule"]
        for t, v in tab.sort_values("imn_tm", ascending=False).iterrows():
            mode, lam = t.split("_")
            lines.append(f"\\texttt{{{mode}}}, {lam} & {v['imn_tm']:.4f} & {v['imn_hybrid']:.4f} \\\\")
        lines += [r"\bottomrule", r"\end{tabular}"]
        (OUT / "reg_table.tex").write_text("\n".join(lines) + "\n")
        M.add("RegRecords", str(len(rows)))
    else:
        pending(OUT / "reg_table.tex", "Phase 1")

    # ---- Phase 4
    if "xai" in stages:
        d = stages["xai"].copy()
        d["family"] = d.dataset.str.extract(r"xai_(\w+?)_rho")[0]
        fig_xai(d, FIG / "xai_gt.pdf")
        arms = [a for a in ["lr", "gbdt", "tabresnet", "imn", "tm", "clause_lr", "imn_tm", "imn_hybrid", "tm_gated"]
                if a in set(d.arm)]
        lines = [r"\begin{tabular}{l" + "ccc" * 3 + "}", r"\toprule",
                 r" & \multicolumn{3}{c}{Gaussian linear} & \multicolumn{3}{c}{Non-linear additive} & "
                 r"\multicolumn{3}{c}{Piecewise constant} \\",
                 r"\cmidrule(lr){2-4}\cmidrule(lr){5-7}\cmidrule(lr){8-10}",
                 r"Method " + r"& AUROC & GT corr.\ $\uparrow$ & infid.\ $\downarrow$ " * 3 + r"\\", r"\midrule"]
        g = d.groupby(["arm", "family"])[["test_auroc", "x_gt_corr", "x_infidelity"]].mean()
        for a in arms:
            cells = []
            for fam in ("linear", "nonlinear", "piecewise"):
                if (a, fam) in g.index:
                    v = g.loc[(a, fam)]
                    cells += [f"{v.test_auroc:.3f}", f"{v.x_gt_corr:.3f}", f"{v.x_infidelity:.3f}"]
                else:
                    cells += ["--"] * 3
            lines.append(" & ".join([NAMES[a]] + cells) + r" \\")
        lines += [r"\bottomrule", r"\end{tabular}"]
        (OUT / "xai_table.tex").write_text("\n".join(lines) + "\n")
        gm = d.groupby(["arm", "family"]).x_gt_corr.mean()
        for a in ("imn", "imn_tm", "tm_gated", "gbdt"):
            for fam in ("linear", "nonlinear", "piecewise"):
                if (a, fam) in gm.index:
                    M.add("Xai" + "".join(ch for ch in a + fam if ch.isalpha()), f"{gm[(a, fam)]:.3f}")
        ga = d.groupby(["arm", "family"]).test_auroc.mean()
        for a in ("lr", "tabresnet", "imn", "imn_tm", "tm"):
            for fam in ("linear", "nonlinear", "piecewise"):
                k = "".join(ch for ch in a + fam if ch.isalpha())
                if (a, fam) in gm.index:
                    if a in ("lr", "tabresnet", "tm"):  # the others are added above
                        M.add("Xai" + k, f"{gm[(a, fam)]:.3f}")
                    M.add("XaiAuc" + k, f"{ga[(a, fam)]:.3f}")
        # paired imn_tm vs imn and vs tm_gated over (task, seed): same data, same test rows
        pv = d.pivot_table(index=["dataset", "seed"], columns="arm", values="x_gt_corr")
        for b in ("imn", "tm_gated", "gbdt"):
            if {"imn_tm", b} <= set(pv.columns):
                dd = (pv["imn_tm"] - pv[b]).dropna()
                k = "".join(ch for ch in b if ch.isalpha())
                M.add(f"XaiVs{k}Mean", f"{dd.mean():+.3f}")
                M.add(f"XaiVs{k}Wins", str(int((dd > 0).sum())))
                M.add(f"XaiVs{k}N", str(len(dd)))
                M.add(f"XaiVs{k}Losses", str(int((dd < 0).sum())))
                M.add(f"XaiVs{k}P", pval(stats.wilcoxon(dd.values).pvalue))
        d["rho"] = d.dataset.str.extract(r"rho([\d.]+)")[0].astype(float)
        for a in ("imn", "imn_tm"):
            k = "".join(ch for ch in a if ch.isalpha())
            r = d[d.family == "linear"].groupby(["rho"]).apply(lambda t: t[t.arm == a].x_gt_corr.mean())
            M.add(f"XaiLinDrop{k}", f"{r.iloc[-1] - r.iloc[0]:+.3f}")
        M.add("XaiRecords", str(len(d)))
    else:
        pending(OUT / "xai_table.tex", "Phase 4")

    # ---- Phase 5
    if "abl" in stages and "main" in stages:
        a_df, m_df = stages["abl"], stages["main"]
        ref = m_df[m_df.seed.isin(a_df.seed.unique())]
        ref_mean = _mean_table(ref).droplevel(1)
        rows = []
        specs = [("tm", "tm50", "TM, 50 clauses/class", "tm", "TmFifty"),
                 ("tm", "tm800", "TM, 800 clauses/class", "tm", "TmEight"),
                 ("imn_tm", "tm50", "IMN-TM on 50-clause TM", "imn_tm", "ImntmFifty"),
                 ("imn_tm", "tm800", "IMN-TM on 800-clause TM", "imn_tm", "ImntmEight"),
                 ("imn_tm", "noinit", "IMN-TM without TM initialisation", "imn_tm", "Noinit"),
                 ("imn_tm_xc", "", "IMN-TM, generator input $[x, c(x)]$", "imn_tm", "Xc"),
                 ("imn_tm_randfr", "", "IMN-TM, random clauses (rate-matched)", "imn_tm", "Randfr"),
                 ("imn_hybrid", "split", "IMN-Hybrid, linear $\\lambda=0.1$", "imn_hybrid", "Split")]
        for arm, tag, label, base, key in specs:
            sub = a_df[(a_df.arm == arm) & (a_df.tag == tag)]
            if sub.empty:
                continue
            sm = sub.groupby("dataset_id").test_auroc.mean()
            dd = (sm - ref_mean[base].reindex(sm.index)).dropna()
            vi = (sm - ref_mean["imn"].reindex(sm.index)).dropna()
            p = stats.wilcoxon(dd.values).pvalue if len(dd) > 1 and np.any(dd.values != 0) else float("nan")
            fid = sub.x_local_acc_k10.mean() if "x_local_acc_k10" in sub else np.nan
            rows.append((label, NAMES[base], len(dd), dd.mean(), int((dd > 0).sum()), int((dd < 0).sum()), p,
                         vi.mean() if base != "tm" else np.nan, fid, key,
                         ref[ref.arm == base].x_local_acc_k10.mean() if base != "tm" else np.nan))
        lines = [r"\begin{tabular}{llcrcccc}", r"\toprule",
                 r"Variant & reference & $n$ & mean $\Delta$ & W/L & $p$ & $\Delta$ vs.\ IMN & fid.\ $k{=}10$ \\",
                 r"\midrule"]
        for r in rows:
            lines.append(f"{r[0]} & {r[1]} & {r[2]} & {r[3]:+.4f} & {r[4]}/{r[5]} & {pval(r[6])} & "
                         f"{fmt(r[7], 4, True)} & {fmt(r[8], 3)} \\\\")
        lines += [r"\bottomrule", r"\end{tabular}"]
        (OUT / "abl_table.tex").write_text("\n".join(lines) + "\n")
        for r in rows:
            k = "Abl" + r[9]
            M.add(k + "Mean", f"{r[3]:+.4f}")
            M.add(k + "Wins", str(r[4]))
            M.add(k + "Losses", str(r[5]))
            M.add(k + "P", pval(r[6]))
            M.add(k + "VsImn", fmt(r[7], 4, True))
            M.add(k + "Fid", fmt(r[8], 2))
            M.add(k + "RefFid", fmt(r[10], 2))
        M.add("AblRecords", str(len(a_df)))
    else:
        pending(OUT / "abl_table.tex", "Phase 5")

    # ---- Tier-2 skips / failures
    skipped = []
    for p in (RESULTS / "tier2").glob("*/*__s*.json") if (RESULTS / "tier2").exists() else []:
        j = json.loads(p.read_text())
        if j.get("status") == "skipped":
            skipped.append(f"{tex_escape(j['dataset'])}/{NAMES.get(j['arm'], j['arm'])}")
    M.add("TiertwoSkipped", str(len(skipped)))
    M.add("TiertwoSkippedList", ", ".join(sorted(set(skipped))) if skipped else "none")
    M.write(OUT / "macros.tex")
    print(f"wrote {len(M.lines)} macros, tables -> {OUT.relative_to(EXP_DIR)}, figures -> {FIG.relative_to(EXP_DIR)}")


if __name__ == "__main__":
    main()
