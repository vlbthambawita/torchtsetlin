def _style():
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams.update({
        "font.family": "serif", "font.size": 8, "axes.labelsize": 8, "axes.titlesize": 8.5,
        "xtick.labelsize": 7, "ytick.labelsize": 7, "legend.fontsize": 7, "axes.edgecolor": MUTED,
        "axes.labelcolor": INK2, "xtick.color": INK2, "ytick.color": INK2, "axes.linewidth": 0.6,
        "axes.spines.top": False, "axes.spines.right": False, "axes.grid": True, "grid.color": GRID,
        "grid.linewidth": 0.5, "axes.axisbelow": True, "text.color": INK, "pdf.fonttype": 42,
        "legend.frameon": False})
    return plt


def fig_gap(df: pd.DataFrame, path: Path, title: str) -> Optional[float]:
    plt = _style()
    m = _mean_table(df).droplevel(0)
    if not {"imn", "imn_tm", "rf", "gbdt", "lr", "tm_gated"} <= set(m.columns):
        return None
    m = m.dropna(subset=["imn", "imn_tm", "rf", "gbdt", "lr"])
    gap = m[["rf", "gbdt"]].max(1) - m[["lr", "imn"]].max(1)
    fig, ax = plt.subplots(figsize=(3.4, 2.7))
    ax.axhline(0, color=MUTED, lw=0.8)
    ax.axvline(0, color=MUTED, lw=0.8)
    for arm, col, mk, lab in (("imn_tm", ORANGE, "o", "IMN-TM $-$ IMN"), ("tm_gated", AQUA, "s", "TM-Gated $-$ IMN")):
        d = m[arm] - m["imn"]
        ax.scatter(gap, d, s=22, color=col, marker=mk, edgecolor="white", linewidth=0.8, label=lab, zorder=3)
    d = m["imn_tm"] - m["imn"]
    r = float(np.corrcoef(gap, d)[0, 1])
    k, b = np.polyfit(gap, d, 1)
    xs = np.linspace(gap.min(), gap.max(), 10)
    ax.plot(xs, k * xs + b, color=ORANGE, lw=1, ls="--", zorder=2)
    for name in d.index:
        if abs(d[name]) > 0.015 or abs(gap[name]) > 0.04:
            right = gap[name] > 0.6 * gap.max()  # keep labels inside the axes
            ax.annotate(name.replace("_", "-"), (gap[name], d[name]), fontsize=6, color=INK2,
                        xytext=(-4 if right else 4, -8 if right else 2), textcoords="offset points",
                        ha="right" if right else "left")
    ax.set_xlabel("tree-ensemble advantage over linear (AUROC)")
    ax.set_ylabel("$\\Delta$ test AUROC vs. IMN")
    ax.set_title(f"{title}; IMN-TM: $r = {r:.2f}$", loc="left", color=INK, fontsize=8, pad=16)
    ax.legend(loc="lower left", bbox_to_anchor=(0.0, 1.0), ncol=2, frameon=False, borderaxespad=0.2)
    fig.tight_layout()
    fig.savefig(path, bbox_inches="tight", pad_inches=0.12)
    plt.close(fig)
    return r


