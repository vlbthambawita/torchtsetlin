def fig_xai(df: pd.DataFrame, path: Path) -> None:
    plt = _style()
    d = df.copy()
    d["family"] = d.dataset.str.extract(r"xai_(\w+?)_rho")[0]
    d["rho"] = d.dataset.str.extract(r"rho([\d.]+)")[0].astype(float)
    fams = [f for f in ("linear", "nonlinear", "piecewise") if f in set(d.family)]
    fig, axes = plt.subplots(1, len(fams), figsize=(6.8, 2.2), sharey=True)
    axes = np.atleast_1d(axes)
    series = (("gbdt", MUTED, "D", ":"), ("imn", BLUE, "o", "-"), ("imn_tm", ORANGE, "o", "-"),
              ("tm_gated", AQUA, "s", "-"))
    for ax, fam in zip(axes, fams):
        g = d[d.family == fam].groupby(["arm", "rho"]).x_gt_corr.mean().unstack("arm")
        for arm, col, mk, ls in series:
            if arm in g:
                ax.plot(g.index, g[arm], color=col, marker=mk, ms=3.5, lw=1.4, ls=ls, label=NAMES[arm])
        ax.set_title({"linear": "Gaussian linear", "nonlinear": "Non-linear additive",
                      "piecewise": "Piecewise constant"}[fam], loc="left")
        ax.set_xlabel("feature correlation $\\rho$")
    axes[0].set_ylabel("corr. with true contributions")
    h, lab = axes[0].get_legend_handles_labels()
    fig.tight_layout()
    fig.legend(h, lab, loc="lower center", bbox_to_anchor=(0.5, 1.0), ncol=len(lab), frameon=False)
    fig.savefig(path, bbox_inches="tight", pad_inches=0.12)
    plt.close(fig)


def fig_ranks(cols: Dict[str, pd.Series], path: Path, arms: List[str]) -> None:
    plt = _style()
    names = list(cols)
    arms = [a for a in arms if all(a in s.index for s in cols.values())]
    arms = sorted(arms, key=lambda a: cols[names[-1]][a])
    fig, ax = plt.subplots(figsize=(3.4, 2.8))
    y = np.arange(len(arms))
    marks = ("o", "D", "s")
    for i, n in enumerate(names):
        ax.scatter([cols[n][a] for a in arms], y + (i - (len(names) - 1) / 2) * 0.22, s=16,
                   color=[FAMILY[a] for a in arms], marker=marks[i % 3], edgecolor="white", lw=0.6,
                   label=n, zorder=3)
    ax.set_yticks(y)
    ax.set_yticklabels([NAMES[a] for a in arms])
    ax.set_xlabel("average rank, test AUROC (lower is better)")
    ax.grid(axis="y", visible=False)
    leg = ax.legend(loc="lower center", bbox_to_anchor=(0.5, 1.0), ncol=len(names), frameon=False)
    for h in leg.legend_handles:
        h.set_color(INK2)
    fig.tight_layout()
    fig.savefig(path, bbox_inches="tight", pad_inches=0.12)
    plt.close(fig)


