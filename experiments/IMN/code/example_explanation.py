"""Worked example for the report: how IMN and IMN-TM explain the same credit-g decision.

    python -m experiments.IMN.code.example_explanation     # -> report/generated/example_fig.tex

Re-trains the main-stage ``imn`` and ``imn_tm`` models of credit-g, split seed 0 (deterministic,
identical to the records in ``results/main``; the script checks the test AUROC against them),
picks the first explained test row on which both models are correct and confident, and writes a
TikZ picture whose every label and number comes from those two models (C2).
"""

from __future__ import annotations

import json

import numpy as np
import torch

from . import data as D
from .arms import run_arm
from .latex_report import OUT, tex_escape
from .metrics import classification_metrics
from .report import RESULTS
from .run import explain_rows_for

DATASET, SEED = 31, 0
MAIN_NN = {"imn": {}, "imn_tm": {"l1_mode": "prior", "weight_norm": 1.0}}


def raw_value(S, col: int, v: float) -> str:
    """Standardised value -> original units for numeric columns; categorical columns keep
    their encoded value (target encoding for binary tasks)."""
    nn = S.info.get("n_numeric", 0)
    if col < nn and "num_mean" in S.info:
        return f"{v * S.info['num_scale'][col] + S.info['num_mean'][col]:.4g}"
    return f"{v:.2f}\\,(enc.)"


def clause_text(S, basis, j: int) -> str:
    """Clause as per-column intervals (thermometer literals of one column merged: the
    conjunction of ``x >= a_i`` and ``x < b_k`` is ``max(a) <= x < min(b)``; equivalent)."""
    boo = basis.booleanizer
    F = boo.n_bool
    lo, hi = {}, {}
    for i in basis.include[j].nonzero().flatten().tolist():
        b = i % F
        col, thr = int(boo.col[b]), float(boo.thr[b])
        if i < F:
            lo[col] = max(lo.get(col, -np.inf), thr)
        else:
            hi[col] = min(hi.get(col, np.inf), thr)
    parts = []
    for col in sorted(set(lo) | set(hi)):
        name = r"\texttt{" + tex_escape(S.feature_names[col]) + "}"
        if col in lo and col in hi:
            parts.append(f"{raw_value(S, col, lo[col])}$\\le${name}$<${raw_value(S, col, hi[col])}")
        elif col in lo:
            parts.append(f"{name}$\\ge${raw_value(S, col, lo[col])}")
        else:
            parts.append(f"{name}$<${raw_value(S, col, hi[col])}")
    return r" $\wedge$ ".join(parts)


def main() -> None:
    S = D.load(DATASET, SEED)
    rows = explain_rows_for(S, 500, SEED)
    res = {a: run_arm(a, S, SEED, "cuda" if torch.cuda.is_available() else "cpu", MAIN_NN[a], {},
                      log=lambda *_: None, explain_rows=rows) for a in ("imn", "imn_tm")}
    for a, r in res.items():
        rec = json.loads((RESULTS / "main" / f"{DATASET}_{S.name}" / f"{a}__s{SEED}.json").read_text())
        auc = classification_metrics(S.y_test, r.proba["test"], 2)["auroc"]
        assert abs(auc - rec["metrics"]["test"]["auroc"]) < 1e-9, (a, auc, rec["metrics"]["test"]["auroc"])
    p_imn, p_tm = res["imn"].proba["test"][rows], res["imn_tm"].proba["test"][rows]
    y = S.y_test[rows]
    ok = ((p_imn > 0.5) == (y == 1)) & ((p_tm > 0.5) == (y == 1)) & (np.abs(p_imn - 0.5) > 0.3) & (np.abs(p_tm - 0.5) > 0.3)
    pos = int(np.flatnonzero(ok)[0])
    dev = res["imn_tm"].info["basis_obj"].include.device
    x = torch.as_tensor(S.X_test[rows[pos]][None], device=dev)
    pr = torch.tensor([pos], device=dev)
    # IMN: w_m(x) x_m
    w = res["imn"].explain.parts(pr)["linear"][0, :, 0]
    contrib = (w * x[0]).cpu().numpy()
    top_f = np.argsort(-np.abs(contrib))[:5]
    # IMN-TM: W_j(x) c_j(x) over active clauses
    basis = res["imn_tm"].info["basis_obj"]
    c = basis.evaluate(x)[0]
    W = res["imn_tm"].explain.parts(pr)["clauses"][0, :, 0]
    cc = (W * c).cpu().numpy()
    act = np.flatnonzero(c.cpu().numpy() > 0)
    top_c = act[np.argsort(-np.abs(cc[act]))][:4]
    share = float(np.abs(cc[top_c]).sum() / max(np.abs(cc[act]).sum(), 1e-12))
    label = S.info["classes"][int(y[pos])]

    scale = 1.5 / max(np.abs(contrib[top_f]).max(), np.abs(cc[top_c]).max())
    L = [r"% generated by code/example_explanation.py -- do not edit",
         r"\begin{tikzpicture}[x=1cm,y=1cm,font=\footnotesize]",
         r"\node[anchor=west,font=\bfseries] at (0,0.55) {IMN: feature impacts $w_m(x)\,x_m$};",
         r"\draw[gaMuted] (5.0,0.25) -- (5.0,-1.75);"]
    for k, f in enumerate(top_f):
        v = contrib[f] * scale
        yk = -k * 0.36
        L.append(f"\\fill[gaBlue,rounded corners=0.6pt] (5.0,{yk:.2f}) rectangle ({5.0 + v:.3f},{yk - 0.22:.2f});")
        name = tex_escape(S.feature_names[f])
        L.append(f"\\node[anchor=east,text=gaInkTwo] at (3.3,{yk - 0.11:.2f}) "
                 f"{{\\texttt{{{name}}}$=${raw_value(S, int(f), float(x[0, f]))}}};")
        L.append(f"\\node[anchor={'west' if v >= 0 else 'east'},font=\\scriptsize,text=gaInkTwo] at "
                 f"({5.0 + v + (0.06 if v >= 0 else -0.06):.3f},{yk - 0.11:.2f}) {{{contrib[f]:+.2f}}};")
    L.append(r"\node[anchor=west,font=\bfseries] at (7.55,0.55) {IMN-TM: active rules, weight $W_j(x)$};")
    for k, j in enumerate(top_c):
        yk = -k * 0.62
        col = "gaOrange"
        L.append(f"\\node[anchor=east,text={col},font=\\small\\bfseries] at (8.4,{yk - 0.11:.2f}) {{{cc[j]:+.2f}}};")
        L.append(f"\\node[anchor=west,draw={col}!50,rounded corners=1.5pt,inner sep=2pt,text width=7.0cm,"
                 f"font=\\scriptsize] at (8.5,{yk - 0.11:.2f}) {{{clause_text(S, basis, int(j))}}};")
    L.append(f"\\node[anchor=west,font=\\scriptsize,text=gaInkTwo] at (7.55,{-len(top_c) * 0.62 - 0.05:.2f}) "
             f"{{top {len(top_c)} of {len(act)} active rules; {100 * share:.0f}\\% of the clause evidence}};")
    L.append(f"\\node[anchor=west,font=\\scriptsize,text=gaInkTwo] at (0,-2.5) "
             f"{{test example {int(rows[pos])}, true class \\texttt{{{tex_escape(label)}}}; "
             f"$P(\\text{{class 1}})$: IMN {p_imn[pos]:.2f}, IMN-TM {p_tm[pos]:.2f}}};")
    L.append(r"\end{tikzpicture}")
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "example_fig.tex").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
