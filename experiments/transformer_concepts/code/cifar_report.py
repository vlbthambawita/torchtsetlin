"""Generate REPORT_CIFAR10.md from results/cifar/*.json (rule C2: no hand-typed numbers).

    python -m experiments.transformer_concepts.code.cifar_report
"""
from __future__ import annotations

import glob
import json
from pathlib import Path
from statistics import mean, stdev

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "results" / "cifar"
CLASSES = ("airplane", "automobile", "bird", "cat", "deer", "dog", "frog", "horse", "ship", "truck")
ARMS = [
    ("flat", "Normal TM (flat)", "`TsetlinMachine` on all 12,288 bits"),
    ("ctm", "Convolutional TM", "`ConvTsetlinMachine`, 4×4 patches, stride 1, position bits (841 patches)"),
    ("pair_self", "Patch TM, no attention", "64 non-overlapping 4×4 patch tokens, each paired only with itself"),
    ("pair_local", "Pair attention, neighbours", "pair clauses Q(token i) ∧ K(token j) ∧ R(dy, dx) ∧ A(i), |dy|, |dx| ≤ 1 (576 pairs)"),
    ("pair", "Pair attention, all pairs", "the same over all 64 × 64 = 4,096 ordered pairs"),
    ("qkv_d1", "Graph TM, depth 1 (no messages)", "`GraphTsetlinMachine` on the 64 patch nodes, coalesced, no message passing"),
    ("qkv", "Q/K/V attention (graph TM, depth 2)", "values = layer-1 clause matches of sender j, hashed messages bound to 16 direction types, OR inbox, queries on receiver i"),
]


def load():
    out = {}
    for p in glob.glob(str(R / "*_e30.json")):
        r = json.loads(Path(p).read_text())
        out[r["key"]] = r
    return out


def pct(v):
    return f"{100 * v:.2f}"


def main():
    recs = load()
    lines = ["# CIFAR-10: normal Tsetlin machines vs transformer-concept TMs", "",
             "Generated by `code/cifar_report.py` from `results/cifar/*.json`; do not edit by hand. Protocol:",
             "`DECISIONS.md` D15–D17; code: `code/cifar.py`. Library `src/torchtsetlin` unchanged.", "",
             "## Setup", "",
             "- Data: CIFAR-10, thermometer Booleanization with 4 thresholds per channel (12 × 32 × 32 bits, the",
             "  `experiments/convtm` cache), the convtm stratified 45,000 / 5,000 train/validation split, the official",
             "  10,000-image test set read once per final run.",
             "- Every arm: 2,000 clauses in total, T = 80, soft literal budget 32, batch 32, 30 epochs, best",
             "  validation epoch kept. Class-wise clauses (200 per class), except the two graph arms, which are",
             "  coalesced (2,000 shared clauses with per-class weights) because that is the graph TM's output layer.",
             "- Specificity s searched on validation with seed 0 (s ∈ {2, 10, 40}; graph arms {2, 10}); finals with",
             "  seeds 1–3 at the chosen s. The Q/K/V arm has one final seed (D17, user decision: it is ~6× slower).", "",
             "| arm | model |", "|---|---|"]
    for a, name, desc in ARMS:
        lines.append(f"| {name} (`{a}`) | {desc} |")
    lines += ["", "## Results", "", "| arm | s | validation (search, seed 0) by s | test accuracy % (seeds) | mean ± SD | train time / run |",
              "|---|---|---|---|---|---|"]
    rows = []
    for a, name, _ in ARMS:
        search = {r["s"]: r["best_val"] for k, r in recs.items() if r["arm"] == a and r["seed"] == 0}
        if not search:
            continue
        s_best = max(search, key=lambda s: (search[s], -s))
        finals = sorted([r for r in recs.values() if r["arm"] == a and r["seed"] > 0 and "test_acc" in r],
                        key=lambda r: r["seed"])
        accs = [r["test_acc"] for r in finals]
        srch = ", ".join(f"s={s:g}: {pct(v)}" for s, v in sorted(search.items()))
        seeds = ", ".join(pct(v) for v in accs) if accs else "–"
        ms = (f"{pct(mean(accs))} ± {100 * stdev(accs):.2f}" if len(accs) > 1 else (pct(accs[0]) if accs else "–"))
        t = f"{mean(r['train_seconds'] for r in finals) / 60:.0f} min" if finals else "–"
        lines.append(f"| {name} | {s_best:g} | {srch} | {seeds} | {ms} | {t} |")
        rows.append((a, name, accs, finals))
    lines += ["", "Train time is the update loop only, on one RTX 3080-class GPU shared with other runs, so it is a",
              "rough cost guide, not a benchmark.", ""]
    # per-class
    lines += ["## Per-class test accuracy (mean over final seeds, %)", "",
              "| arm | " + " | ".join(CLASSES) + " |", "|---|" + "---|" * len(CLASSES)]
    for a, name, accs, finals in rows:
        if not finals:
            continue
        pc = [mean(r["test_acc_per_class"][c] for r in finals) for c in range(10)]
        lines.append(f"| {name} | " + " | ".join(f"{100 * v:.1f}" for v in pc) + " |")
    lines.append("")
    # comparisons
    by = {a: accs for a, _, accs, _ in rows}

    def d(a, b):
        if not by.get(a) or not by.get(b):
            return None
        return 100 * (mean(by[a]) - mean(by[b]))

    lines += ["## What the numbers say", ""]
    comp = [("pair", "flat", "attention TM vs the normal flat TM"),
            ("pair", "pair_self", "attention vs the same tokens without attention (the attention effect itself)"),
            ("pair_local", "pair_self", "neighbour attention vs no attention"),
            ("pair", "pair_local", "global vs neighbour attention"),
            ("ctm", "pair", "the convolutional TM vs the attention TM"),
            ("qkv", "qkv_d1", "Q/K/V message passing vs the same graph TM without it (seed 1 only for qkv)"),
            ("qkv", "pair", "Q/K/V attention vs pair attention")]
    lines += ["| comparison | difference of means (pp) |", "|---|---|"]
    for a, b, txt in comp:
        v = d(a, b)
        if v is not None:
            lines.append(f"| {txt} | {v:+.2f} |")
    lines.append("")
    dh = ROOT / "results" / "htm" / "dh2a.json"
    if dh.exists():
        h = json.loads(dh.read_text())
        lines += ["**Why Q/K/V message passing does not help (D-H2a, `THEORY_HTM.md` H2.2).** In the trained Q/K/V model a mean",
                  f"{100 * h['f_mean']:.1f} % of the 2,000 layer-1 clause parts match at a patch (empty parts, which match everywhere: {h['empty_layer0_parts']}),",
                  f"so each receiving patch's 1,024-bit inbox is {100 * h['inbox_density_mean']:.1f} % full on average",
                  f"(minimum {100 * h['inbox_density_min']:.1f} %; H2.2 predicts {100 * h['inbox_density_predicted_H2_2']:.1f} %). Saturation sets in at",
                  f"f ≈ {100 * h['f_threshold_for_q_099']:.1f} %. A nearly all-ones inbox carries almost no information about the senders;",
                  f"yet {100 * h['inbox_literal_share']:.1f} % of the included literals are inbox literals. On a bit that is almost always 1, a",
                  "positive literal is a near-free condition and a negated one fires only on the rare empty slot, so the",
                  "learner spends literals on bits that carry little signal: the independence approximation of H2.2",
                  "slightly overstates the density (it ignores correlated senders), but the saturation is real.", ""]
    tail = ROOT / "report_cifar_tail.md"
    if tail.exists():
        lines += [tail.read_text()]
    (ROOT / "REPORT_CIFAR10.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
