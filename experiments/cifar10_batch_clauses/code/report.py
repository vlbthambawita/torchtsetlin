"""Progress and results of cifar10_batch_clauses, generated from results/*.json only.

Usage: python code/report.py            # REPORT.md + results/summary.json
       python code/report.py --status   # short progress table (status.sh)
"""

import argparse
import glob
import time

from common import (
    BATCHES,
    CLAUSES_OF,
    FINAL,
    MODELS,
    PROG,
    RESULTS,
    flat_choice,
    jobs,
    read_json,
    write_json,
)

ARMS = ["pricing", "pilot", "grid", "control_seq", "control_T"]


def recs(arm):
    return {r["tag"]: r for r in (read_json(f) for f in sorted(glob.glob(str(RESULTS / arm / "*.json"))))
            if r and "tag" in r}


def status():
    L = [f"cifar10_batch_clauses status, {time.strftime('%Y-%m-%d %H:%M')}", "",
         f"{'arm':12s} {'total':>5s} {'done':>5s} {'oom':>4s} {'running':>7s} {'todo':>5s}"]
    running = []
    for arm in ARMS:
        js, rs = jobs(arm), recs(arm)
        st = [rs.get(j["tag"], {}).get("status") for j in js]
        n_run = sum(s == "running" for s in st)
        L.append(f"{arm:12s} {len(js):5d} {st.count('done'):5d} {st.count('oom'):4d} {n_run:7d} "
                 f"{sum(s not in FINAL and s != 'running' for s in st):5d}")
        for j in js:
            r = rs.get(j["tag"])
            if r and r.get("status") == "running" and r.get("curve"):
                c = r["curve"][-1]
                running.append(f"  {arm}/{j['tag']}: epoch {c['epoch']}, val {c['val_acc']:.2f} "
                               f"(best {c['best_val_acc']:.2f}, wait {c['epochs_since_improvement']}), "
                               f"test {c['test_acc']:.2f}, {c['train_s'] + c['val_s'] + c['test_s']:.0f} s/epoch, "
                               f"gpu {r['env'].get('gpu_slot')}")
    ch = flat_choice()
    L += ["", f"flat pilot choice: {'T_ref=%d s=%g' % ch if ch else 'not yet'}"]
    stop = read_json(RESULTS / "STOP.json")
    if stop or (PROG / "STOP").exists():
        L.append(f"STOPPED: {stop['reason'] if stop else 'STOP file present'}")
    if running:
        L += ["", "running (last finished epoch):"] + running
    return "\n".join(L)


def fmt(v, nd=2):
    return "–" if v is None else f"{v:.{nd}f}"


def cell(r, key, nd):
    if r is None:
        return "–"
    if r.get("status") == "oom":
        return "OOM"
    if r.get("status") != "done":
        return "…"
    mark = {"max_epochs": "†", "time_cap": "‡"}.get(r.get("stop_reason"), "")
    return fmt(r.get(key), nd) + mark


def grid_table(rs, model, key, nd, t_mode="scaled"):
    rows = ["| C/class | " + " | ".join(f"B={b}" for b in BATCHES) + " |",
            "|---" * (len(BATCHES) + 1) + "|"]
    for c in CLAUSES_OF[model]:
        rows.append(f"| {c} | " + " | ".join(
            cell(rs.get(f"{model}_c{c}_b{b}_T{t_mode}_s0"), key, nd) for b in BATCHES) + " |")
    return "\n".join(rows)


def b_star(rs, model, c, tol=1.0):
    """D12: largest B whose test accuracy is within tol pp of the B = 1 cell (seed 0 only)."""
    ref = rs.get(f"{model}_c{c}_b1_Tscaled_s0")
    if not ref or ref.get("status") != "done":
        return None
    ok = [b for b in BATCHES if (r := rs.get(f"{model}_c{c}_b{b}_Tscaled_s0")) and r.get("status") == "done"
          and r["test_acc_at_best"] >= ref["test_acc_at_best"] - tol]
    return max(ok) if ok else None


def full_report():
    md = ["# cifar10_batch_clauses: batch size × clauses per class on CIFAR-10", "",
          "<!-- Generated by code/report.py from results/*.json; do not hand-edit. -->", "",
          f"Updated {time.strftime('%Y-%m-%d %H:%M')}. Statistic: test accuracy at the best-validation epoch "
          "(validation = 5 000 held-out training images). † stopped at 500 epochs, ‡ at the 24 h cap, "
          "OOM = does not fit the GPU, … = running/queued. Seed 0. Plan: `plans/cifar10-batch-clauses.md`.", "",
          "```", status(), "```", ""]
    summary = {}
    g = recs("grid")
    gpus = sorted({r["env"].get("gpu", "?") for r in g.values() if r.get("env")})
    md.append(f"GPUs: {', '.join(gpus) or '–'}.")
    for m in MODELS:
        md += ["", f"## {m}", "", "### Test accuracy at best epoch (%)", "", grid_table(g, m, "test_acc_at_best", 2),
               "", "### Best epoch", "", grid_table(g, m, "best_epoch", 0),
               "", "### Train s/epoch (mean)", "", grid_table(g, m, "train_s_per_epoch_mean", 1),
               "", "### GPU hours to the best epoch", "", grid_table(
                   {k: dict(v, gpu_h=(v.get("gpu_s_to_best") or 0) / 3600) for k, v in g.items()}, m, "gpu_h", 2),
               "", "B\\*(C), largest B within 1.0 pp of B=1: " + ", ".join(
                   f"{c}: {b_star(g, m, c) or '–'}" for c in CLAUSES_OF[m])]
        summary[m] = {f"c{c}_b{b}": {k: g[t].get(k) for k in ("status", "test_acc_at_best", "best_val_acc",
                                                             "best_epoch", "epochs_run", "stop_reason",
                                                             "train_s_per_epoch_mean", "gpu_s_to_best",
                                                             "peak_gpu_mib")}
                      for c in CLAUSES_OF[m] for b in BATCHES if (t := f"{m}_c{c}_b{b}_Tscaled_s0") in g}
    p = recs("pilot")
    md += ["", "## Flat pilot (C = 2 000, B = 32, ≤ 60 epochs)", "", "| T_ref | s | best val | @ epoch | test there |",
           "|---|---|---|---|---|"]
    for j in jobs("pilot"):
        r = p.get(j["tag"])
        md.append(f"| {j['pilot'][0]} | {j['pilot'][1]:g} | {cell(r, 'best_val_acc', 2)} | "
                  f"{cell(r, 'best_epoch', 0)} | {cell(r, 'test_acc_at_best', 2)} |")
    ch = read_json(RESULTS / "pilot" / "choice.json")
    md.append(f"\nChoice: {'T_ref=%d, s=%g' % (ch['T_ref'], ch['s']) if ch and 'T_ref' in ch else 'pending'}.")
    for arm, title in (("control_T", "T fixed at T_ref (control)"), ("control_seq", "Sequential feedback (control)")):
        rs = recs(arm)
        md += ["", f"## {title}", "", "| run | test @ best | best epoch | grid cell (T scaled / B=1) |", "|---|---|---|---|"]
        for j in jobs(arm):
            r = rs.get(j["tag"])
            ref = g.get(f"{j['model']}_c{j['clauses']}_b{1 if j['sequential'] else j['batch']}_Tscaled_s0")
            md.append(f"| {j['tag']} | {cell(r, 'test_acc_at_best', 2)} | {cell(r, 'best_epoch', 0)} | "
                      f"{cell(ref, 'test_acc_at_best', 2)} |")
    pr = recs("pricing")
    md += ["", "## Pricing (200 timed updates; s/epoch = 45 000 / B updates + validation + test)", "",
           "| run | ms/update | train s/epoch | eval s/epoch | peak MiB |", "|---|---|---|---|---|"]
    for j in jobs("pricing"):
        r = pr.get(j["tag"])
        if r and r.get("status") == "oom":
            md.append(f"| {j['tag']} | OOM | | | |")
        elif r:
            md.append(f"| {j['tag']} | {r['ms_per_update']:.1f} | {r['train_s_per_epoch']:.0f} | "
                      f"{r['eval_s_per_epoch']:.0f} | {r['peak_gpu_mib']:.0f} |")
    (PROG / "REPORT.md").write_text("\n".join(md) + "\n")
    write_json(summary, RESULTS / "summary.json")
    print(f"wrote {PROG / 'REPORT.md'} and results/summary.json")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--status", action="store_true")
    a = ap.parse_args()
    print(status()) if a.status else full_report()
