"""Build REPORT.md, results/composite.json and the paper's LaTeX table/numbers from results/*.json.

Composite (arXiv:2406.00704 Eqs. 4-5; the ``Scores`` class of the authors' CIFAR10lastepochs.py):
for each epoch, ``alpha_t = max - min`` of specialist t's test class sums, ``y = argmax_i sum_t
c_t^i / alpha_t``; the reported statistic is the mean and sample variance of that accuracy over
epochs 226-250 (Table IV). Specialists: the same statistic over their own per-epoch accuracy.

Usage: python code/report.py [--no-paper]
"""

import argparse
import glob
import time

import numpy as np

from common import CACHE, PAPER, PROG, RESULTS, new_record, read_json, test_labels, write_json
from specialists import (COMPOSITE_TABLE_IV, CLAUSE_COLUMNS, EPOCHS, LAST_EPOCHS, ORDER,
                         SPECIALISTS)

TOL_PP = 1.5                                            # README.md, M8 (fixed before any run)
PLAIN = [s for s in ORDER if not s.endswith("_aug")]
TEAMS = {"all22": ORDER, "plain11": PLAIN}


def runs():
    out = {}
    for f in sorted(glob.glob(str(RESULTS / "*_seed0.json"))):
        r = read_json(f)
        if r.get("kind") == "specialist":
            out[r["spec"]] = r
    return out


def sums_dir(r):
    return CACHE / "class_sums" / f"{r['spec']}_c{r['clauses']}_seed{r['seed']}"


def composite(team, rs, y):
    """Per-epoch composite accuracy over the epochs every member has; None if a member is missing."""
    if not all(s in rs for s in team):
        return None
    last = min(len(rs[s]["curve"]) for s in team)
    curve = []
    for e in range(1, last + 1):
        votes = 0
        for s in team:
            c = np.load(sums_dir(rs[s]) / f"e{e:03d}.npy")
            votes = votes + c / (c.max() - c.min())
        curve.append(float((votes.argmax(1) == y).mean() * 100))
    return curve


def last25(curve):
    if len(curve) < EPOCHS:
        return None
    a = np.array(curve[EPOCHS - LAST_EPOCHS:EPOCHS])
    return {"mean": float(a.mean()), "variance": float(a.var(ddof=1)), "sd": float(a.std(ddof=1))}


def verdict(ours, paper):
    if ours is None:
        return "running"
    return "REPRODUCED" if abs(ours - paper) <= TOL_PP else "GAP"


def build():
    rs = runs()
    y = test_labels()
    rows = []
    for sid in ORDER:
        cfg = SPECIALISTS[sid]
        r = rs.get(sid)
        row = {"id": sid, "name": cfg["name"], "window": cfg["window"], "T": cfg["T"], "s": cfg["s"],
               "weighted": cfg["weighted"]}
        if r is None:
            row.update(status="queued", clauses=None)
            rows.append(row)
            continue
        curve = [c["test_acc"] for c in r["curve"]]
        stat = last25(curve)
        p = cfg["paper"][r["clauses"]]
        row.update(status=r["status"], clauses=r["clauses"], epochs_done=len(curve),
                   latest=curve[-1] if curve else None, last25=stat,
                   paper=p, paper_64k=cfg["paper"][64000],
                   delta=None if stat is None else stat["mean"] - p["mean"],
                   verdict=verdict(stat and stat["mean"], p["mean"]),
                   train_s=float(np.mean([c["train_s"] for c in r["curve"]])) if curve else None,
                   test_s=float(np.mean([c["test_s"] for c in r["curve"]])) if curve else None,
                   peak_gib=max((c.get("peak_gib", 0) for c in r["curve"]), default=None),
                   n_train=r["data"]["n_train"], torchtsetlin=r["env"]["torchtsetlin"],
                   gpu=r["env"].get("gpu"))
        rows.append(row)
    teams = {}
    for name, team in TEAMS.items():
        curve = composite(team, rs, y)
        stat = last25(curve) if curve else None
        paper = dict(zip(("mean", "variance"), COMPOSITE_TABLE_IV[CLAUSE_COLUMNS.index(64000)])) \
            if name == "all22" else None
        teams[name] = {"members": team, "epochs_done": len(curve) if curve else 0,
                       "latest": curve[-1] if curve else None, "curve": curve, "last25": stat,
                       "paper": paper,
                       "verdict": verdict(stat and stat["mean"], paper["mean"]) if paper else None}
    return rows, teams


def fmt(v, nd=1):
    return "–" if v is None else f"{v:.{nd}f}"


def write_report(rows, teams):
    L = ["# toolbox_cifar10: torchtsetlin at the Optimized Toolbox's best setting",
         "", "<!-- Generated by code/report.py from results/*.json; do not hand-edit. -->", "",
         f"Updated {time.strftime('%Y-%m-%d %H:%M')}. Paper: Grønningsæter et al. 2024, arXiv:2406.00704, "
         "Table IV (64 000 clauses per class; mean ± sample variance over epochs 226–250). Ours: "
         f"torchtsetlin, the paper's Table III hyper-parameters, one run per specialist. Verdict: "
         f"REPRODUCED if within {TOL_PP} pp of the paper (fixed in README.md before any run).", "",
         "## Specialists", "",
         "| Specialist | Clauses/class | Paper | Ours (last 25) | Δ pp | Verdict | Epochs | Latest | Train s/epoch | Test s | Peak GiB |",
         "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        if r["status"] == "queued":
            L.append(f"| {r['name']} | – | {SPECIALISTS[r['id']]['paper'][64000]['mean']} | – | – | queued | 0 | – | – | – | – |")
            continue
        st = r["last25"]
        ours = f"{st['mean']:.2f} ± {st['variance']:.2f}" if st else "–"
        L.append(f"| {r['name']} | {r['clauses']:,} | {r['paper']['mean']} ± {r['paper']['variance']} | {ours} | "
                 f"{fmt(r['delta'], 2)} | {r['verdict']} | {r['epochs_done']} | {fmt(r['latest'], 2)} | "
                 f"{fmt(r['train_s'], 0)} | {fmt(r['test_s'], 0)} | {fmt(r['peak_gib'])} |")
    L += ["", "## Composites", "", "| Team | Paper | Ours (last 25) | Verdict | Epochs (all members) | Latest |",
          "|---|---|---|---|---|---|"]
    for name, t in teams.items():
        st = t["last25"]
        p = f"{t['paper']['mean']} ± {t['paper']['variance']}" if t["paper"] else "not published"
        ours = f"{st['mean']:.2f} ± {st['variance']:.2f}" if st else "–"
        L.append(f"| {name} ({len(t['members'])} specialists) | {p} | {ours} | {t['verdict'] or '–'} | "
                 f"{t['epochs_done']} | {fmt(t['latest'], 2)} |")
    L += ["", "Deviations: D1 batched feedback (batch 50; the paper's tmu updates per example); "
          "D2 HOG specialists at 16 000 clauses/class (64 000 and 32 000 do not fit 24 GB), compared "
          "with the paper's 16 000 cell, and included at 16 000 in the composites. See README.md."]
    (PROG / "REPORT.md").write_text("\n".join(L) + "\n")


def tex_num(key, v):
    return f"\\expandafter\\def\\csname R@tb/{key}\\endcsname{{{v}}}"


def write_paper(rows, teams):
    out = PAPER / "generated"
    hdr = "% generated by experiments/toolbox_cifar10/code/report.py from results/*.json; do not edit"
    T = [hdr, r"\begin{tabular}{@{}lrrrr@{}}", r"\toprule",
         r"Specialist (Table III settings) & clauses & paper & \lib{} & $\Delta$ \\", r"\midrule"]
    for r in rows:
        name = r["name"].replace("Augmented ", "Aug.\\ ").replace("Histogram of Oriented Gradients", "HOG") \
            .replace("Color Thermometers", "Colour Therm.").replace("Thresholding", "Thr.") \
            .replace("Edge Detection", "Edges").replace("Otsu's", "Otsu")
        if r["status"] == "queued":
            T.append(f"{name} & -- & {SPECIALISTS[r['id']]['paper'][64000]['mean']:.1f} & -- & -- \\\\")
            continue
        st = r["last25"]
        ours = f"{st['mean']:.1f}{{\\tiny$\\pm${st['variance']:.2f}}}" if st else \
            f"\\textit{{{r['latest']:.1f}}}{{\\tiny ep {r['epochs_done']}}}"
        d = f"{r['delta']:+.1f}" if r["delta"] is not None else "--"
        T.append(f"{name} & {r['clauses'] // 1000}k & {r['paper']['mean']:.1f}{{\\tiny$\\pm${r['paper']['variance']:.2f}}}"
                 f" & {ours} & {d} \\\\")
    T.append(r"\midrule")
    t = teams["all22"]
    st = t["last25"]
    ours = f"{st['mean']:.1f}{{\\tiny$\\pm${st['variance']:.2f}}}" if st else \
        (f"\\textit{{{t['latest']:.1f}}}{{\\tiny ep {t['epochs_done']}}}" if t["latest"] else "--")
    d = f"{st['mean'] - t['paper']['mean']:+.1f}" if st else "--"
    T += [f"TM Composite, all 22 & 64k & {t['paper']['mean']:.1f}{{\\tiny$\\pm${t['paper']['variance']:.2f}}} & {ours} & {d} \\\\",
          r"\bottomrule", r"\end{tabular}"]
    (out / "toolbox_table.tex").write_text("\n".join(T) + "\n")

    N = [hdr]
    done = [r for r in rows if r.get("last25")]
    for r in done:
        N.append(tex_num(f"acc/{r['id']}", f"{r['last25']['mean']:.1f}"))
        N.append(tex_num(f"paper/{r['id']}", f"{r['paper']['mean']:.1f}"))
        N.append(tex_num(f"delta/{r['id']}", f"{r['delta']:+.1f}"))
        N.append(tex_num(f"trainh/{r['id']}", f"{r['train_s'] * EPOCHS / 3600:.0f}"))
        N.append(tex_num(f"epochs/{r['id']}", f"{r['train_s']:.0f}"))
    for name, t in teams.items():
        if t["last25"]:
            N.append(tex_num(f"acc/{name}", f"{t['last25']['mean']:.1f}"))
    N.append(tex_num("n/done", str(len(done))))
    N.append(tex_num("n/reproduced", str(sum(r["verdict"] == "REPRODUCED" for r in done))))
    if done:
        N.append(tex_num("delta/meanabs", f"{np.mean([abs(r['delta']) for r in done]):.1f}"))
        N.append(tex_num("gpuh/total", f"{sum((r['train_s'] + r['test_s']) * EPOCHS for r in done) / 3600:.0f}"))
    (out / "toolbox_numbers.tex").write_text("\n".join(N) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-paper", action="store_true")
    args = ap.parse_args()
    rows, teams = build()
    write_json(new_record("composite", tolerance_pp=TOL_PP, specialists=rows,
                          teams={k: {kk: vv for kk, vv in v.items()} for k, v in teams.items()}),
               RESULTS / "composite.json")
    write_report(rows, teams)
    if not args.no_paper:
        write_paper(rows, teams)
    n = sum(1 for r in rows if r.get("last25"))
    print(f"{n}/22 specialists finished; " + ", ".join(
        f"{k}: {v['epochs_done']} epochs" for k, v in teams.items()))


if __name__ == "__main__":
    main()
