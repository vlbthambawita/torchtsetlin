"""Regenerate the white paper's literature-review data from the SQLite catalog.

Run from the repository root after ``python benchmarks/literature/build_catalog.py``:

    python whitepaper/data/regen_literature.py

Reads docs/assets/literature/literature.db and writes
  data/lit-stats.tex       \\newcommand macros for every count quoted in the text
  data/lit-top.csv         the most-used datasets (papers using each)
  data/lit-types.csv       datasets per coarse data type
  data/lit-categories.csv  papers per category
  data/lit-best.csv        best reported test accuracy: TM model vs non-TM baseline
so no literature number in the white paper or the summary report is typed by hand.
"""

import csv
import sqlite3
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DB = ROOT / "docs" / "assets" / "literature" / "literature.db"
OUT = Path(__file__).resolve().parent

# Free-text data types -> coarse classes; first match wins, so "synthetic tabular" is synthetic.
TYPE_RULES = [("synthetic", ("synthetic", "board game")),
              ("text", ("text",)),
              ("image", ("image",)),
              ("tabular", ("tabular",)),
              ("time series, sensor, audio", ("time-series", "sensor", "audio")),
              ("graph, sequence, molecular", ("graph", "sequence", "molecular"))]
CATEGORY_NAMES = {"foundations": "Foundations", "hardware": "Hardware accelerators",
                  "generative_sequence": "Generative / sequence", "medical_clinical": "Medical / clinical",
                  "image_classification": "Image classification", "segmentation": "Segmentation",
                  "privacy_federated": "Privacy / federated"}
# TREC is left out: its best "TM" row is a BiLSTM-attention network over TM word embeddings (a hybrid).
BEST_DATASETS = ["mnist", "fashion-mnist", "kuzushiji-mnist", "cifar-10", "imdb", "reuters-21578-r8"]
LABEL = {"mnist": "MNIST", "fashion-mnist": "Fashion-MNIST", "kuzushiji-mnist": "K-MNIST",
         "cifar-10": "CIFAR-10", "imdb": "IMDb", "reuters-21578-r8": "Reuters R8"}


def coarse(t):
    t = (t or "").lower()
    for name, keys in TYPE_RULES:
        if any(k in t for k in keys):
            return name
    return "other"


def write_csv(name, header, rows):
    with open(OUT / name, "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(header)
        w.writerows(rows)


def main():
    con = sqlite3.connect(f"file:{DB}?mode=ro", uri=True)
    q = lambda sql, *a: con.execute(sql, a).fetchall()  # noqa: E731
    one = lambda sql, *a: q(sql, *a)[0][0]  # noqa: E731

    stats = {
        "litNpapers": one("SELECT COUNT(*) FROM papers"),
        "litNdatasets": one("SELECT COUNT(*) FROM datasets"),
        "litNresults": one("SELECT COUNT(*) FROM results"),
        "litNusages": one("SELECT COUNT(*) FROM dataset_usages"),
        "litNmetrics": one("SELECT COUNT(DISTINCT metric) FROM results"),
        "litNtm": one("SELECT COUNT(*) FROM results WHERE is_tm = 1"),
        "litNbaseline": one("SELECT COUNT(*) FROM results WHERE is_tm = 0"),
        "litNproposed": one("SELECT COUNT(*) FROM results WHERE is_proposed = 1"),
        "litNranked": one("SELECT COUNT(*) FROM results WHERE better IS NOT NULL"),
        "litNflagged": one("SELECT COUNT(*) FROM papers WHERE caution IS NOT NULL"),
        "litNdownload": one("SELECT COUNT(*) FROM datasets WHERE download_url IS NOT NULL"),
        "litYearMin": one("SELECT MIN(year) FROM papers"),
        "litYearMax": one("SELECT MAX(year) FROM papers"),
        "litDbKiB": round(DB.stat().st_size / 1024),
    }
    with open(OUT / "lit-stats.tex", "w") as fh:
        fh.write("% Generated by data/regen_literature.py from docs/assets/literature/literature.db.\n")
        for k, v in stats.items():
            text = str(v) if k.startswith("litYear") else f"{v:,}".replace(",", "{,}")
            fh.write(f"\\newcommand{{\\{k}}}{{{text}}}\n")

    top = q("SELECT dataset_id, n_papers FROM datasets ORDER BY n_papers DESC, dataset_id LIMIT 10")
    write_csv("lit-top.csv", ["dataset", "papers"], top)

    counts = {}
    for (t,) in q("SELECT data_type FROM datasets"):
        counts[coarse(t)] = counts.get(coarse(t), 0) + 1
    write_csv("lit-types.csv", ["type", "datasets"], sorted(counts.items(), key=lambda kv: -kv[1]))

    write_csv("lit-categories.csv", ["category", "papers"],
              [(CATEGORY_NAMES.get(c, c), n) for c, n in
               q("SELECT category, COUNT(*) FROM papers GROUP BY 1 ORDER BY 2 DESC")])

    # Best reported *test* accuracy (no stated split counts as test) in centralised classification:
    # papers without a caution flag, and not the federated ones, whose personalised per-client
    # accuracies on non-IID splits are not comparable with a centralised test accuracy.
    rows = []
    for ds in BEST_DATASETS:
        def best(is_tm, ds=ds):
            r = q("""SELECT r.value FROM results r JOIN papers p USING (paper_id)
                     WHERE r.dataset_id = ? AND r.metric = 'accuracy' AND r.unit = '%'
                       AND COALESCE(NULLIF(r.split, ''), 'test') = 'test'
                       AND p.caution IS NULL AND p.category != 'privacy_federated'
                       AND r.is_tm = ?
                     ORDER BY r.value DESC LIMIT 1""", ds, is_tm)
            return r[0][0] if r else ""
        rows.append((LABEL[ds], best(1), best(0)))
    write_csv("lit-best.csv", ["dataset", "tm", "baseline"], rows)
    print("wrote", ", ".join(sorted(p.name for p in OUT.glob("lit-*"))))


if __name__ == "__main__":
    main()
